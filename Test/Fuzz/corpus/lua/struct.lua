local s = newstruct(16)
local get, set = xlua.genaccessor(4, 4)
set(s, 42)
assert(get(s) == 42)
local fget, fset = xlua.genaccessor(8, 9)
fset(s, 1.5)
local c = xlua.structclone(s)
assert(get(c) == 42 and fget(c) == 1.5)
return pcall(xlua.genaccessor, -1, 0), pcall(get, newstruct(2)), pcall(xlua.structclone, {})

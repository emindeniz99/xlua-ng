// Runs the general Lua suite (Test/UnitTest: StreamingAssets/main.lua and the
// C# fixtures it calls) inside a player, for Test/UnityMatrix/il2cpp_suite.py.
// It does what Test/UnitTest/xLuaTest/Main.cs does (require 'main' in the
// suite's LuaEnvSingleton) and adds what a headless run needs:
//
// - every log line (Lua's print goes to Debug.Log) is also appended to
//   xlua-suite.log in Application.persistentDataPath, which survives a full
//   logcat ring buffer, and the summary lines of luaunit_compat.lua ("[luaunit
//   normal] Ran N tests ...") go to xlua-suite-result.txt with a last line
//   XLUA_SUITE_DONE ok|error;
// - Resources/xlua_suite_env.txt sets the XLUA_EXPECT_* variables of the
//   native library the player was built with (Tools/presets.py), as
//   run_managed.py does for the host suite, through the C library's setenv,
//   which both os.getenv and Environment.GetEnvironmentVariable read (an
//   empty value reads as null from C# on IL2CPP, so il2cpp_suite.py writes
//   none);
// - the StreamingAssets files listed in Resources/xlua_suite_files.txt are
//   copied to persistentDataPath/StreamingAssets: on Android they are inside
//   the APK, where io.open cannot reach LuaTestCommon.existingFilePath. Without
//   the StreamingAssets searcher (XLUA_NO_STREAMING_ASSETS_LOADER, the minimal
//   preset) package.path points at the copies in both of the suite's envs, as
//   run_managed.py points it at Test/UnitTest: Lua's file searcher comes after
//   the Resources searcher, as the StreamingAssets one does, so
//   testRequire2LoadLua still finds D in Resources first. With the searcher,
//   xLua's own StreamingAssets searcher loads the suite (on Android through
//   the AssetManager since 2026-10-29, through WWW before).
// <xlua-preset> generated by Tools/presets.py from docs/design/presets.md; do not edit
#if XLUA_PRESET_MINIMAL
#define XLUA_NO_STREAMING_ASSETS_LOADER
#define XLUA_NO_SIGNATURE_LOADER
#define XLUA_NO_TEMPLATE
#if !XLUA_UTIL
#define XLUA_NO_UTIL
#endif
#define XLUA_NO_PROFILER
#define XLUA_NO_LOAD_ASSEMBLY
#define XLUA_LOCK_METATABLES
#define XLUA_RESTRICT_GETMETATABLE
#define XLUA_LOCK_XLUA_TABLE
#define XLUA_RESTRICT_PRIVATE_ACCESS
#define XLUA_REDUCED_DEBUG
#if !XLUA_REFLECTION
#define XLUA_NO_REFLECTION
#endif
#if !XLUA_NO_GCM
#define GEN_CODE_MINIMIZE
#endif
#endif
#if (UNITY_EDITOR || DEVELOPMENT_BUILD || XLUA_GENERAL) && !XLUA_NO_BRIDGE_CHECKS
#define XLUA_BRIDGE_CHECKS
#endif
// </xlua-preset>
using System;
using System.Collections;
using System.Collections.Generic;
using System.IO;
using System.Runtime.InteropServices;
using System.Text;
using UnityEngine;
using UnityEngine.Networking;
using XLua;

public class XluaSuiteRunner : MonoBehaviour
{
    public const string LogName = "xlua-suite.log";
    public const string ResultName = "xlua-suite-result.txt";

    readonly object gate = new object();
    StreamWriter log;
    readonly List<string> summary = new List<string>();

    [DllImport("libc")]
    static extern int setenv(string name, string value, int overwrite);

    void OnLog(string message, string stackTrace, LogType type)
    {
        lock (gate)
        {
            if (log == null) return;
            log.Write(message);
            log.Write('\n');
            if ((type == LogType.Exception || type == LogType.Error) && !string.IsNullOrEmpty(stackTrace))
            {
                log.Write(stackTrace);
                log.Write('\n');
            }
            if (message.Contains("[luaunit ")) summary.Add(message);
        }
    }

    static string[] Lines(string resource)
    {
        var asset = Resources.Load<TextAsset>(resource);
        if (asset == null) return new string[0];
        return asset.text.Split(new[] { '\n', '\r' }, StringSplitOptions.RemoveEmptyEntries);
    }

    IEnumerator Start()
    {
        string dir = Application.persistentDataPath;
        Directory.CreateDirectory(dir);
        File.Delete(Path.Combine(dir, ResultName));
        log = new StreamWriter(Path.Combine(dir, LogName), false, new UTF8Encoding(false)) { AutoFlush = true };
        // One line per Lua print; errors keep their stack.
        Application.SetStackTraceLogType(LogType.Log, StackTraceLogType.None);
        Application.SetStackTraceLogType(LogType.Warning, StackTraceLogType.None);
        Application.logMessageReceivedThreaded += OnLog;
        Debug.Log("XLUA_SUITE_START unity=" + Application.unityVersion + " platform=" + Application.platform
            + " backend=" + (IsIl2Cpp() ? "IL2CPP" : "Mono") + " debug=" + Debug.isDebugBuild);

        foreach (var line in Lines("xlua_suite_env"))
        {
            int eq = line.IndexOf('=');
            if (eq <= 0) continue;
            string name = line.Substring(0, eq), value = line.Substring(eq + 1);
            if (setenv(name, value, 1) != 0) Debug.LogError("XLUA_SUITE setenv failed for " + name);
            Debug.Log("XLUA_SUITE_ENV " + name + "=" + value + " (Environment: " + Quoted(Environment.GetEnvironmentVariable(name)) + ")");
        }
        // How the runtime reads a variable set to the empty string (Mono gives "").
        setenv("XLUA_SUITE_EMPTY_PROBE", "", 1);
        Debug.Log("XLUA_SUITE_EMPTY_ENV: Environment.GetEnvironmentVariable gives "
            + Quoted(Environment.GetEnvironmentVariable("XLUA_SUITE_EMPTY_PROBE")) + " for an empty variable");

        string copies = Path.Combine(dir, "StreamingAssets");
        string root = Application.streamingAssetsPath;
        foreach (var relative in Lines("xlua_suite_files"))
        {
            string url = root.Contains("://") ? root + "/" + relative : "file://" + root + "/" + relative;
            using (var request = UnityWebRequest.Get(url))
            {
                yield return request.SendWebRequest();
                if (request.result != UnityWebRequest.Result.Success)
                {
                    Debug.LogError("XLUA_SUITE cannot read " + url + ": " + request.error);
                    continue;
                }
                string target = Path.Combine(copies, relative);
                Directory.CreateDirectory(Path.GetDirectoryName(target));
                File.WriteAllBytes(target, request.downloadHandler.data);
            }
        }
        yield return null;

        float started = Time.realtimeSinceStartup;
        string error = null;
        try
        {
            LuaEnv luaenv = LuaEnvSingleton.Instance;
#if XLUA_NO_STREAMING_ASSETS_LOADER
            foreach (var env in new[] { luaenv, LuaEnvSingletonForTest.Instance })
            {
                var package = env.Global.Get<LuaTable>("package");
                package.Set("path", copies + "/?.lua;" + package.Get<string>("path"));
                package.Dispose();
            }
#endif
            luaenv.DoString("require 'main'");
        }
        catch (Exception e)
        {
            error = e.ToString();
            Debug.LogError("XLUA_SUITE_ERROR " + error);
        }
        string done = "XLUA_SUITE_DONE " + (error == null ? "ok" : "error") + " in "
            + (Time.realtimeSinceStartup - started).ToString("0.0") + " s";
        Debug.Log(done);
        lock (gate)
        {
            var result = new StringBuilder();
            foreach (var line in summary) result.Append(line).Append('\n');
            if (error != null) result.Append("XLUA_SUITE_ERROR ").Append(error.Split('\n')[0]).Append('\n');
            result.Append(done).Append('\n');
            File.WriteAllText(Path.Combine(dir, ResultName), result.ToString());
        }
    }

    static string Quoted(string s)
    {
        return s == null ? "null" : "\"" + s + "\"";
    }

    static bool IsIl2Cpp()
    {
#if ENABLE_IL2CPP
        return true;
#else
        return false;
#endif
    }

    void OnDestroy()
    {
        Application.logMessageReceivedThreaded -= OnLog;
        lock (gate)
        {
            if (log != null) log.Dispose();
            log = null;
        }
    }
}

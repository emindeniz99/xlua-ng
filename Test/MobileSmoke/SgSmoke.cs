using System;
using System.Linq;
using System.Runtime.CompilerServices;
using XLua;

// Through the generated wrapper Lua does not see Hidden; through reflection it does.
[assembly: BlackList(typeof(SgApi), "Hidden")]
// Not wrapped: Lua calls SgApi.Reflected through reflection, so only the
// generated link.xml fragment keeps it under High stripping.
[assembly: DoNotGen(typeof(SgApi), "Reflected")]
#if XLUA_NO_REFLECTION
// Strict minimal has no reflection fallback, so everything Lua uses needs
// generated bindings: XluaSmoke's SmokeApi (elsewhere it goes through
// reflection on purpose) and the fields of the [GCOptimize] struct SgApi.Swap
// returns ([GCOptimize] only generates its pusher and reader).
[assembly: LuaCallCSharp(typeof(SmokeApi))]
[assembly: LuaCallCSharp(typeof(SgPoint))]
#endif

namespace System.Runtime.CompilerServices
{
    // init accessors need this type; .NET Standard 2.1 does not have it.
    internal static class IsExternalInit { }
}

// A delegate bridge generated into this assembly (a closed static delegate over DelegateBridge).
[CSharpCallLua]
public delegate int SgTwice(int x);

// Pushed and read without boxing by the generated pusher.
[GCOptimize]
public struct SgPoint
{
    public int X;
    public int Y;
}

[LuaCallCSharp]
public class SgApi
{
    public static int Hidden = 7;

    public static int Twice(int x)
    {
        return x * 2;
    }

    public static SgPoint Swap(SgPoint p)
    {
        return new SgPoint { X = p.Y, Y = p.X };
    }

    public static int Apply(SgTwice f, int x)
    {
        return f(x);
    }

    // [assembly: DoNotGen] above.
    public static string Reflected(string s)
    {
        return "reflected:" + s;
    }

    // A C# exception becomes a Lua error inside the wrapper, or with
    // GEN_CODE_MINIMIZE in the native trampoline's C# entry.
    public static int Fail(int x)
    {
        throw new InvalidOperationException("sg-fail-" + x);
    }
}

// An init-only setter: the wrapper falls back to reflection for it (the
// fallback warning in development players), and link.xml keeps the setter.
[LuaCallCSharp]
public class SgInit
{
    public int Locked { get; init; }
}

// Reached only through reflection; [ReflectionUse] keeps all of it. Under
// XLUA_NO_REFLECTION it only keeps it from stripping: Lua gets the error.
[ReflectionUse]
public class SgReflected
{
    public int Value = 5;

    public int Plus(int x)
    {
        return Value + x;
    }
}

// Wrapped, with private members that only xlua.private_accessible reaches:
// no C# code reads or writes secret or calls Doubled, so the wrapper keeps
// neither. Where xlua.private_accessible exists (legacy, or HOTFIX_ENABLE),
// the generator's link.xml keeps the whole type (preserve="all", owner
// decision Q75 of 2026-10-29); without it High stripping removes both and Lua
// reads nil.
[LuaCallCSharp]
public class SgPrivate
{
    public int Visible = 1;
#pragma warning disable 0649
    private int secret;
#pragma warning restore 0649

    private int Doubled()
    {
        return secret * 2;
    }
}

// Wrapped, with a public generic method that no wrapper calls (no parameter
// uses T) and no C# code calls: Lua reaches it only by name, through
// xlua.get_generic_method. [ReflectionUse] keeps the whole type in every preset.
[LuaCallCSharp, ReflectionUse]
public class SgGeneric
{
    public int Visible = 1;

    public static string NameOf<T>()
    {
        return typeof(T).Name;
    }
}

// The same without [ReflectionUse]: legacy's link.xml keeps the type whole
// (Q75), strict minimal's keeps only what the wrapper calls, so High stripping
// removes NameOf there (Q84 of 2026-10-29: link.xml stays narrow).
[LuaCallCSharp]
public class SgGenericBare
{
    public int Visible = 1;

    public static string NameOf<T>()
    {
        return typeof(T).Name;
    }
}

// Nothing configures or calls this: High stripping removes it (a static check
// of the stripped Assembly-CSharp.dll shows it).
public class SgUnused
{
    public static int Unrelated()
    {
        return 1;
    }
}

public static class SgSmoke
{
    static void Check(bool value, string name)
    {
        if (!value) throw new Exception("XLUA_NG_SMOKE_FAIL: source generator: " + name);
    }

    [MethodImpl(MethodImplOptions.NoInlining)]
    public static string Run(LuaEnv env)
    {
        var assembly = typeof(SgApi).Assembly;
        var generated = assembly.GetTypes().Where(t => t.Namespace != null && t.Namespace.StartsWith("XLua.Generated.")).ToArray();
        Check(generated.Any(t => t.Name == "Bindings"), "XLua.Generated.*.Bindings in " + assembly.GetName().Name);
        Check(generated.Any(t => t.Name.StartsWith("W_") && t.Name.Contains("SgApi")), "the SgApi wrapper: " + string.Join(",", generated.Select(t => t.Name).ToArray()));

        // The wrapper: the blacklisted field is not there, the methods are.
        Check(Convert.ToInt64(env.DoString("return CS.SgApi.Twice(21)")[0]) == 42, "wrapped method");
        Check((bool)env.DoString("return CS.SgApi.Hidden == nil")[0], "the wrapper leaves out the blacklisted Hidden");

        // DoNotGen: reflection, kept by link.xml.
        Check((string)env.DoString("return CS.SgApi.Reflected('x')")[0] == "reflected:x", "DoNotGen method through reflection");

        // [GCOptimize] struct in and out.
        Check((bool)env.DoString("local p = CS.SgApi.Swap({X = 1, Y = 2}); return p.X == 2 and p.Y == 1")[0], "GCOptimize struct from a table and back");

        // The init-only setter falls back to reflection.
        Check(Convert.ToInt64(env.DoString("local o = CS.SgInit(); o.Locked = 3; return o.Locked")[0]) == 3, "init-only setter through reflection");

#if XLUA_NO_REFLECTION
        // [ReflectionUse] does not open reflection for its type (presets.md, "Reflection
        // fallback and CodeEmit as implemented"): constructing it raises the error that
        // names the type and how to bind it. The class table itself stays.
        Check((bool)env.DoString("return typeof(CS.SgReflected) ~= nil")[0], "typeof of a type without generated bindings");
        var refused = (string)env.DoString("local ok, e = pcall(function() return CS.SgReflected() end) return ok and 'no error' or tostring(e)")[0];
        Check(refused.Contains("cannot construct SgReflected") && refused.Contains("has no generated bindings") && refused.Contains("XLUA_NO_REFLECTION"),
            "[ReflectionUse] type without the reflection fallback: " + refused);
        string reflection = "no reflection fallback, ";
#else
        // [ReflectionUse]: constructor, field and method through reflection.
        Check(Convert.ToInt64(env.DoString("local r = CS.SgReflected(); return r:Plus(r.Value)")[0]) == 10, "[ReflectionUse] type through reflection");
        string reflection = "";
#endif

#if !XLUA_RESTRICT_PRIVATE_ACCESS || HOTFIX_ENABLE
        // xlua.private_accessible on a wrapped type: its private field and method
        // through reflection. Under High stripping only the generator's link.xml
        // keeps them; without its preserve="all" this reads "false,nil,..." .
        var accessible = (string)env.DoString(@"
            xlua.private_accessible(CS.SgPrivate)
            local p = CS.SgPrivate()
            local set = pcall(function() p.secret = 21 end)
            local _, got = pcall(function() return p.secret end)
            local _, doubled = pcall(function() return p:Doubled() end)
            return tostring(set) .. ',' .. tostring(got) .. ',' .. tostring(doubled)")[0];
        Check(accessible == "true,21,42", "private members of a [LuaCallCSharp] type through xlua.private_accessible (set,get,call): " + accessible);
        reflection += "private_accessible, ";
#endif

        // A public generic method through xlua.get_generic_method, in every preset.
        var generic = GenericNameOf(env, "SgGeneric");
        Check(generic == "true,String", "a public generic method of a [LuaCallCSharp, ReflectionUse] type through xlua.get_generic_method: " + generic);
        var bare = GenericNameOf(env, "SgGenericBare");
        if (bare == "true,String")
        {
            reflection += "get_generic_method, ";
        }
        else
        {
#if XLUA_RESTRICT_PRIVATE_ACCESS
            // Stripped (strict minimal, High stripping): the error names the
            // type and the method, and in an IL2CPP player how to keep it.
            Check(bare.StartsWith("error: ") && bare.Contains("SgGenericBare has no public generic method 'NameOf'.")
#if ENABLE_IL2CPP && !UNITY_EDITOR
                && bare.Contains("stripping may have removed it: add [ReflectionUse] to SgGenericBare")
#endif
                , "the error of xlua.get_generic_method for a stripped generic method: " + bare);
            UnityEngine.Debug.Log("XLUA_NG_SMOKE_INFO: SgGenericBare.NameOf was stripped; " + bare);
            reflection += "get_generic_method (stripped one raised), ";
#else
            Check(false, "a public generic method of a [LuaCallCSharp] type through xlua.get_generic_method: " + bare);
#endif
        }

        // A C# exception reaches Lua as "c# exception:..." in both modes.
        Check((bool)env.DoString("local ok, e = pcall(CS.SgApi.Fail, 5) return not ok and string.find(tostring(e), 'c# exception:', 1, true) ~= nil and string.find(tostring(e), 'sg-fail-5', 1, true) ~= nil")[0],
            "a C# exception as a Lua error");
        string mode = "";
#if GEN_CODE_MINIMIZE
        // GCM: the wrapper functions are (ObjectTranslator, IntPtr, int) methods, not native callbacks.
        var wrapper = generated.First(t => t.Name.StartsWith("W_") && t.Name.Contains("SgApi"));
        var functions = wrapper.GetMethods(System.Reflection.BindingFlags.Static | System.Reflection.BindingFlags.NonPublic)
            .Where(m => m.Name.StartsWith("_m_")).ToArray();
        Check(functions.Length > 0 && functions.All(m => m.GetParameters().Length == 3 && m.GetParameters()[0].ParameterType == typeof(ObjectTranslator)),
            "GCM wrapper functions: " + string.Join(",", functions.Select(m => m.ToString()).ToArray()));
        mode = "GCM, " + functions.Length + " methods of " + wrapper.Name + ", ";
#endif

        // The generated delegate bridge in this assembly, closed over the DelegateBridge.
        string bridge = Bridge(env);
        Check(Convert.ToInt64(env.DoString("return CS.SgApi.Apply(function(x) return x + 1 end, 41)")[0]) == 42, "Lua function as an SgTwice argument");
        return "source generator (" + reflection + mode + generated.Length + " generated types, bridge " + bridge + ")";
    }

    // "true,String" when T.NameOf<string>() works, "nil" or "error: ..." otherwise.
    static string GenericNameOf(LuaEnv env, string type)
    {
        return (string)env.DoString(@"
            local ok, nameOf = pcall(xlua.get_generic_method, CS." + type + @", 'NameOf')
            if not ok then return 'error: ' .. tostring(nameOf) end
            if nameOf == nil then return 'nil' end
            local okCall, r = pcall(function() return nameOf(CS.System.String)() end)
            return tostring(okCall) .. ',' .. tostring(r)")[0];
    }

    // In its own frame, so that the delegate is gone before LuaEnv.Dispose.
    [MethodImpl(MethodImplOptions.NoInlining)]
    static string Bridge(LuaEnv env)
    {
        var f = env.DoString("return function(x) return x * 2 end")[0] as LuaFunction;
        var twice = f.Cast<SgTwice>();
        f.Dispose();
        Check(twice(21) == 42, "SgTwice from Lua");
        Check(twice.Method.IsStatic, "bridge is static: " + twice.Method);
        Check(twice.Method.Name.StartsWith("__Gen_Delegate_Imp"), "bridge method: " + twice.Method.Name);
        Check(twice.Method.DeclaringType.Assembly == typeof(SgApi).Assembly, "bridge in Assembly-CSharp: " + twice.Method.DeclaringType.AssemblyQualifiedName);
        Check(twice.Target is DelegateBridge, "bridge closed over its DelegateBridge: " + twice.Target);
        return twice.Method.DeclaringType.FullName + "." + twice.Method.Name;
    }
}

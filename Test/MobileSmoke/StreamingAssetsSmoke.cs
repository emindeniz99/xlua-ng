// require from StreamingAssets in a player (prepare.py --streaming-assets, which
// writes the modules below Assets/StreamingAssets/xlua_sa and defines
// XLUA_SMOKE_STREAMING_ASSETS; owner decision Q83 of 2026-10-29):
//
// - with the StreamingAssets searcher (legacy) through require alone, without
//   it (minimal) through env.AddLoader(StreamingAssetsLoader.Load);
// - first on a worker thread that then exits, so the reader starts there
//   (Android: the AssetManager lookup and the thread's Java VM attachment);
// - 20 modules on the main thread, timed in five fresh LuaEnvs, a nested one
//   (xlua_sa.a.b.c is xlua_sa/a/b/c.lua) and a missing one (the error text);
// - no log message from the reader (upstream warned for every file).
//
// It logs XLUA_NG_SA_TIMING lines (ms for the 20 modules, per round) and returns
// a part of the pass line. Failures are collected and thrown at the end, so a
// player of an older tree still logs its timing.
// <xlua-preset> generated by Tools/presets.py from docs/design/presets.md; do not edit

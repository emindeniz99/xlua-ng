using System;
using System.Collections.Generic;
using System.Diagnostics;
using System.Threading;
using UnityEngine;
using XLua;

public static class StreamingAssetsSmoke {
 public const int Modules = 20;
 const int Rounds = 5;

 public static string Run() {
  var failures = new List<string>();
  var logged = new List<string>();
  Application.LogCallback collect = (message, stack, type) => { lock (logged) logged.Add(type + ": " + message); };
  Application.logMessageReceivedThreaded += collect;
  string mode;
  try {
#if UNITY_WEBGL && !UNITY_EDITOR
   mode = WebGL(failures);
#else
   mode = Load(failures);
#endif
  } finally {
   Application.logMessageReceivedThreaded -= collect;
  }
  lock (logged) {
   foreach (var line in logged) {
    if (line.IndexOf("StreamingAssets", StringComparison.OrdinalIgnoreCase) >= 0 && line.IndexOf("XLUA_NG_SA_TIMING", StringComparison.Ordinal) < 0) {
     failures.Add("the reader logged: " + line);
    }
   }
  }
  if (failures.Count > 0) throw new Exception("XLUA_NG_SMOKE_FAIL: StreamingAssets: " + string.Join("; ", failures.ToArray()));
  return mode;
 }

 static LuaEnv NewEnv() {
  var env = new LuaEnv();
#if XLUA_NO_STREAMING_ASSETS_LOADER
  env.AddLoader(StreamingAssetsLoader.Load);
#endif
  return env;
 }

#if XLUA_NO_STREAMING_ASSETS_LOADER
 const string Reader = "StreamingAssetsLoader";
 const string MissingText = "no such file 'xlua_sa.missing' in CustomLoaders!";
#else
 const string Reader = "searcher";
 const string MissingText = "no such file 'xlua_sa/missing.lua' in streamingAssetsPath!";
#endif

#if !(UNITY_WEBGL && !UNITY_EDITOR)
 static string Load(List<string> failures) {
  // A worker thread first: the reader's first use, and a thread that exits afterwards.
  string worker = null;
  Exception workerError = null;
  var thread = new Thread(() => {
   try {
    using (var env = NewEnv()) worker = (string)env.DoString("return require('xlua_sa.a.b.c')")[0];
   } catch (Exception e) { workerError = e; }
  });
  thread.Start();
  if (!thread.Join(30000)) failures.Add("the worker thread's require did not finish in 30 s");
  else if (workerError != null) failures.Add("require on a worker thread: " + workerError.Message);
  else if (worker != "nested a.b.c") failures.Add("require on a worker thread returned " + worker);

  var times = new double[Rounds];
  for (int round = 0; round < Rounds; round++) {
   using (var env = NewEnv()) {
    var watch = Stopwatch.StartNew();
    try {
     env.DoString("for i = 1, " + Modules + " do local m = require(string.format('xlua_sa.m%02d', i)); assert(m.id == i, 'module ' .. i) end");
    } catch (Exception e) {
     failures.Add("round " + round + ": " + e.Message);
    }
    watch.Stop();
    times[round] = watch.Elapsed.TotalMilliseconds;
    if (round == 0) {
     try {
      var nested = env.DoString("local m, data = require('xlua_sa.a.b.c'); return m, data");
      if ((string)nested[0] != "nested a.b.c") failures.Add("nested module returned " + nested[0]);
      if (nested[1] != null && (string)nested[1] != "xlua_sa/a/b/c.lua") failures.Add("nested module's loader data " + nested[1]);
      var missing = env.DoString("return pcall(require, 'xlua_sa.missing')");
      string message = missing[1] as string ?? "";
      if ((bool)missing[0] || message.IndexOf(MissingText, StringComparison.Ordinal) < 0) {
       failures.Add("missing module: " + message);
      }
     } catch (Exception e) {
      failures.Add("nested or missing module: " + e.Message);
     }
    }
   }
  }
  var parts = new string[Rounds];
  for (int i = 0; i < Rounds; i++) parts[i] = times[i].ToString("F2", System.Globalization.CultureInfo.InvariantCulture);
  UnityEngine.Debug.Log("XLUA_NG_SA_TIMING: " + Reader + " " + Modules + " modules, ms per round (the first starts the reader): " + string.Join(" ", parts));
  return "StreamingAssets " + Reader + " (worker thread, nested, missing, " + Modules + " modules in " + parts[0] + " ms, then " + parts[Rounds - 1] + " ms)";
 }
#else
 // WebGL: no synchronous read; require's message says why, Load throws.
 static string WebGL(List<string> failures) {
  using (var env = NewEnv()) {
   var result = env.DoString("return pcall(require, 'xlua_sa.a.b.c')");
   string message = result[1] as string ?? "";
   if ((bool)result[0] || message.IndexOf("cannot be read synchronously on WebGL", StringComparison.Ordinal) < 0) {
    failures.Add("WebGL require: " + message);
   }
  }
  return "StreamingAssets " + Reader + " (WebGL error)";
 }
#endif
}

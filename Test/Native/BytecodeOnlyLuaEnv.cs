// LuaEnv on a bytecode-only native library (CMake XLUA_BYTECODE_ONLY), for
// Test/Native/bytecode_luaenv.py. The library has no compiler, so LuaEnv's own
// Lua source (init_xlua, the removal of libraries, the pairs helper, xlua.util,
// perf.profiler, xlua.memory) must come from the precompiled copies the library
// carries (LuaEnv.LoadBuiltinChunk, build/xlua_chunkc.c), and the test's own
// scripts are precompiled by the driver (BytecodeOnlyLuaEnv.lua).
//
//     mono BytecodeOnlyLuaEnv.exe <folder with main.luac and libs.luac> <modules>
//
// <modules> names the embedded modules the library carries ("util,profiler,memory",
// the CMake options XLUA_BYTECODE_UTIL ...); the others must fail with a message.
// XLUA_BYTECODE_TEST_GEN: compiled with the xLua source generator, whose
// wrapper the checks then require. The defines the driver passes (XLUA_LOCK_METATABLES ...)
// reach init_xlua as its arguments; the script checks their effect.
// <xlua-preset> generated by Tools/presets.py from docs/design/presets.md; do not edit
#if XLUA_PRESET_MINIMAL
#define XLUA_NO_STREAMING_ASSETS_LOADER
#define XLUA_NO_SIGNATURE_LOADER
#define XLUA_NO_TEMPLATE
#if !XLUA_UTIL
#define XLUA_NO_UTIL
#endif
#define XLUA_NO_PROFILER
#define XLUA_NO_LOAD_ASSEMBLY
#define XLUA_LOCK_METATABLES
#define XLUA_CHECK_OBJECTS
#define XLUA_CHECK_STRUCT_ACCESSORS
#define XLUA_RESTRICT_GETMETATABLE
#define XLUA_CHECK_OBJECT_CACHE
#define XLUA_LOCK_XLUA_TABLE
#define XLUA_RESTRICT_PRIVATE_ACCESS
#define XLUA_REDUCED_DEBUG
#endif
// </xlua-preset>
using System;
using System.Collections.Generic;
using System.IO;
using XLua;

[LuaCallCSharp]
public class BytecodeOnlyTarget
{
    public int Value = 7;

    public static int Twice(int x)
    {
        return x * 2;
    }

    public int Add(int a, int b)
    {
        return a + b + Value;
    }

    public List<int> Numbers()
    {
        return new List<int> { 5, 6 };
    }

    public Dictionary<string, int> Named()
    {
        return new Dictionary<string, int> { { "a", 1 }, { "b", 2 } };
    }
}

[CSharpCallLua]
public delegate int BytecodeOnlyIntFunc(int x);

public static class BytecodeOnlyLuaEnv
{
    static int failures;

    static void Check(bool ok, string what)
    {
        Console.WriteLine((ok ? "ok   " : "FAIL ") + what);
        if (!ok)
        {
            failures++;
        }
    }

    static bool Throws(Action action, string text)
    {
        try
        {
            action();
        }
        catch (Exception e)
        {
            if (e.Message.Contains(text))
            {
                return true;
            }
            Console.WriteLine("  unexpected message: " + e.Message);
            return false;
        }
        return false;
    }

    public static int Main(string[] args)
    {
        string folder = args[0];
        var modules = new List<string>((args.Length > 1 ? args[1] : "").Split(','));
        bool locked = false, lockXlua = false, hotfix = true, generated = false, memory = false;
#if XLUA_LOCK_METATABLES
        locked = true;
#endif
#if XLUA_LOCK_XLUA_TABLE
        lockXlua = true;
#endif
#if XLUA_RESTRICT_PRIVATE_ACCESS && !HOTFIX_ENABLE
        hotfix = false;
#endif
#if XLUA_BYTECODE_TEST_GEN
        generated = true;
#endif
#if XLUA_MEMORY_DIAGNOSTICS
        memory = modules.Contains("memory");
#endif
        using (var env = new LuaEnv())
        {
            Check(true, "new LuaEnv() on a bytecode-only library");
            Check(Throws(() => env.DoString("return 1"), "text chunks are not supported in this build"),
                "a text chunk is refused");
            env.AddLoader((ref string file) =>
            {
                string path = Path.Combine(folder, file + ".luac");
                return File.Exists(path) ? File.ReadAllBytes(path) : null;
            });
            var options = env.NewTable();
            options.Set("locked", locked);
            options.Set("lock_xlua", lockXlua);
            options.Set("hotfix", hotfix);
            options.Set("memory", memory);
            options.Set("util", modules.Contains("util"));
            options.Set("profiler", modules.Contains("profiler"));
            options.Set("target", new BytecodeOnlyTarget());
            env.Global.Set("TEST", options);
            object[] result = env.DoString(File.ReadAllBytes(Path.Combine(folder, "main.luac")), "@main.lua");
            Check(result.Length == 1 && "ok".Equals(result[0]), "main.lua: " + (result.Length > 0 ? result[0] : "no result"));
            var twice = env.Global.Get<BytecodeOnlyIntFunc>("lua_twice");
            Check(twice != null && twice(21) == 42, "a Lua function as a C# delegate");
            Check(Throws(() => env.DoString(File.ReadAllBytes(Path.Combine(folder, "error.luac")), "@error.lua"), "error.lua:2:"),
                "a runtime error in a precompiled chunk names its line");
            options.Dispose();
            twice = null;
            env.FullGc();
        }
        // LuaOptions: the libraries a script sees, through the precompiled remove_libraries chunk.
        using (var env = new LuaEnv(new LuaOptions { Libraries = LuaLibs.All & ~(LuaLibs.Io | LuaLibs.Os) }))
        {
            object[] result = env.DoString(File.ReadAllBytes(Path.Combine(folder, "libs.luac")), "@libs.lua");
            Check(result.Length == 1 && "ok".Equals(result[0]), "LuaOptions.Libraries without io and os: " + (result.Length > 0 ? result[0] : "no result"));
        }
        Type wrapper = Array.Find(typeof(BytecodeOnlyTarget).Assembly.GetTypes(), t => t.Namespace != null
            && t.Namespace.StartsWith("XLua.Generated.") && t.Name.StartsWith("W_BytecodeOnlyTarget_"));
        Check(generated == (wrapper != null), generated ? "the generated wrapper is compiled in" : "reflection only (no generated wrapper)");
        Console.WriteLine(failures == 0 ? "XLUA_BYTECODE_LUAENV_PASS" : "XLUA_BYTECODE_LUAENV_FAIL: " + failures);
        return failures == 0 ? 0 : 1;
    }
}

local function show(v)
  local t = type(v)
  if t == "userdata" then return "ud:" .. tostring(v):gsub(": %-?%d+$", "") end
  if t == "number" then return (math.type and math.type(v) or "n") .. ":" .. tostring(v) end
  return t .. ":" .. tostring(v)
end
local function t(name, f)
  local ok, a, b = pcall(f)
  local msg
  if ok then msg = "ok " .. show(a) .. (b ~= nil and (" " .. show(b)) or "")
  else msg = "err " .. tostring(a):match("^[^\n]*") end
  print(name .. " = " .. msg)
end

def validate(options, assemblies, plugin_dir=None):
    if plugin_dir is None:
        result = xluagenerate(["--validate"] + options + assemblies, check=False)
    else:
        # Only plugin_dir is searched for the native plugin.
        env = dict(os.environ, LD_LIBRARY_PATH=str(plugin_dir), DYLD_LIBRARY_PATH=str(plugin_dir))
        cmd = [a.mono, plugin_dir / "XLuaGenerate.exe", "--validate"] + options + assemblies
        print("+", " ".join(str(c) for c in cmd), flush=True)
        result = subprocess.run([str(c) for c in cmd], cwd=plugin_dir, env=env,
                                stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True)
        print(result.stdout, end="")
    found = [line[len("problem: "):] for line in result.stdout.splitlines() if line.startswith("problem: ")]
    expect(result.returncode == (1 if found else 0), "--validate exit code %d for %d problems" % (result.returncode, len(found)))
    return found


def expect_problems(found, wanted, what):
    unmatched = [w for w in wanted if not any(w in f for f in found)]
    expect(not unmatched and len(found) == len(wanted),
           "%s: expected %d problems matching %s, got:\n  %s" % (what, len(wanted), unmatched, "\n  ".join(found)))
    print("LUACATS_VALIDATE_PASS: %s, %d problems" % (what, len(found)))



def tool_env(extra=None):
    env = dict(os.environ)
    env["LD_LIBRARY_PATH"] = str(tools) + os.pathsep + env.get("LD_LIBRARY_PATH", "")
    env["DYLD_LIBRARY_PATH"] = str(tools) + os.pathsep + env.get("DYLD_LIBRARY_PATH", "")
    env.update(extra or {})
    return env


def xluagenerate(args, env=None, exe="XLuaGenerate.exe", check=True, culture=None):
    """Runs a generator build from tools; with culture, in-process under CultureLauncher.exe."""
    cmd = [a.mono] + ([tools / "CultureLauncher.exe", culture] if culture else []) + [tools / exe] + list(args)
    print("+", " ".join(str(c) for c in cmd), flush=True)
    result = subprocess.run([str(c) for c in cmd], cwd=tools, env=tool_env(env),
                            stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True)
    print(result.stdout, end="")
    if check and result.returncode != 0:
        raise SystemExit("XLuaGenerate exited with %d" % result.returncode)
    return result


def generate(assemblies, root, options=(), env=None, exe="XLuaGenerate.exe", clean=True, culture=None):
    """Generates into root/LuaTypes, so that the .luarc.json lands in root."""
    if clean and root.exists():
        shutil.rmtree(root)
    root.mkdir(parents=True, exist_ok=True)
    defs = root / "LuaTypes"
    log = xluagenerate(["--luacats"] + list(options) + assemblies + [defs], env=env, exe=exe, culture=culture).stdout
    return defs, log


def tree(root):
    return sorted(str(f.relative_to(root)) for f in root.rglob("*") if f.is_file())


def golden(name, mode):
    for overlay in overlays[mode]:
        if (overlay / name).exists():
            return overlay / name
    return expected / name


def same_tree(left, right):
    """Differences between two generated trees, byte for byte."""
    problems = []
    if tree(left) != tree(right):
        problems.append("file lists differ: %s / %s" % (sorted(set(tree(left)) - set(tree(right))),
                                                         sorted(set(tree(right)) - set(tree(left)))))
    for name in sorted(set(tree(left)) & set(tree(right))):
        if not filecmp.cmp(left / name, right / name, shallow=False):
            problems.append("%s differs" % name)
    return problems


def check_golden(generated, mode):
    """Compares with the expected files for mode, or rewrites them with --update."""
    if a.update:
        if not overlays[mode]:
            shutil.rmtree(expected, ignore_errors=True)
            shutil.copytree(generated, expected)
            print("Updated", expected)
            return
        target, rest = overlays[mode][0], overlays[mode][1:]
        shutil.rmtree(target, ignore_errors=True)
        for name in tree(generated):
            base = next((o / name for o in rest if (o / name).exists()), expected / name)
            if not base.exists() or not filecmp.cmp(generated / name, base, shallow=False):
                (target / name).parent.mkdir(parents=True, exist_ok=True)
                shutil.copy2(generated / name, target / name)
        print("Updated", target)
        return
    failures = []
    names = set(tree(expected))
    for overlay in overlays[mode]:
        if overlay.exists():
            names |= set(tree(overlay))
    if set(tree(generated)) != names:
        failures.append("file lists differ:\n  only generated: %s\n  only expected: %s" % (
            sorted(set(tree(generated)) - names), sorted(names - set(tree(generated)))))
    for name in sorted(set(tree(generated)) & names):
        if not filecmp.cmp(generated / name, golden(name, mode), shallow=False):
            failures.append(subprocess.run(["diff", "-u", str(golden(name, mode)), str(generated / name)],
                                           stdout=subprocess.PIPE, text=True).stdout)
    if failures:
        print("\n".join(failures))
        raise SystemExit("LuaCATS %s output differs from the expected files; rerun with --update if intended" % mode)
    print("LUACATS_GOLDEN_PASS: %s, %d files match" % (mode, len(tree(generated))))


def expect(condition, message):
    if not condition:
        raise SystemExit("FAIL: " + message)



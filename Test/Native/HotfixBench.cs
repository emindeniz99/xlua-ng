// What hotfix costs at run time (docs/research/hotfix.md, "Measured cost").
//
// hotfix_bench.py compiles this file with the xLua sources and the source
// generator twice: without HOTFIX_ENABLE (nothing is injected) and with it,
// injected by XLuaHotfixInject. size_report.py's +hfbench variants put it into
// an IL2CPP player, where HotfixBenchProbe (Test/MobileSmoke) runs it.
//
// Each case is a loop of calls and reports ns per call (median and minimum of
// the runs, the loop included):
//
//   plain, plain_noinline       a method that is never injected: the cost of
//                               the call itself, inlined or not
//   field, field_noinline       the same method in a [Hotfix] type (field
//                               mode: a static field load and a branch)
//   intkey, intkey_noinline     the same in a [Hotfix(HotfixFlag.IntKey)] type
//                               (a call to the assembly's HotfixBridges.Get)
//   check_list                  hand-written: the process-wide IntKey check,
//                               HotfixDelegateBridge.xlua_get_hotfix_flag (a
//                               P/Invoke on iOS, a managed array read elsewhere)
//   check_native                hand-written: the same check as a P/Invoke into
//                               Assets/Plugins/iOS/HotfixFlags.cpp, as iOS has it
//                               (on the host a library hotfix_bench.py compiles
//                               from that file; in the Android player the file
//                               compiled into the player, called through __Internal)
//   check_bool_array            hand-written: a static bool[] indexed by the
//                               method id, the managed form the backlog proposed
//   check_slot_call             hand-written: a call to a copy of the generated
//                               HotfixBridges.Get (what intkey runs, without injection)
//   check_slot_inline           hand-written: the same array read in the method
//                               itself, as an injector could write it
//   lock_pair                   lock (o) {} on an object no other thread holds
//   delegate_call, table_get    C# -> Lua entries, which take the env's lock
//                               under HOTFIX_ENABLE and THREAD_SAFE
//   lua_object_arg, lua_instance_call  Lua -> C# calls that look up the env's
//                               translator (ObjectTranslatorPool.Find), per call
//                               in Lua's loop
//   lua_string_arg, lua_string_return  Lua -> C# calls with a string argument
//                               (read from Lua) and a string result (pushed into
//                               Lua) of 10 ASCII characters
//   field_patched, intkey_patched  with HOTFIX_ENABLE: the method patched from
//                               Lua (the lock, the Lua call and the conversions)
//

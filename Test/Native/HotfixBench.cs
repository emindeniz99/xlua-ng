    public class Plain
    {
        public int Add(int a, int b) { return a + b; }
        [MethodImpl(MethodImplOptions.NoInlining)]
        public int AddNoInline(int a, int b) { return a + b; }
    }

    [Hotfix]
    public class FieldMode
    {
        public int Add(int a, int b) { return a + b; }
        [MethodImpl(MethodImplOptions.NoInlining)]
        public int AddNoInline(int a, int b) { return a + b; }
        // Patched from Lua for the *_patched cases.
        [MethodImpl(MethodImplOptions.NoInlining)]
        public int AddPatched(int a, int b) { return a + b; }
    }

    [Hotfix(HotfixFlag.IntKey)]
    public class KeyMode
    {
        public int Add(int a, int b) { return a + b; }
        [MethodImpl(MethodImplOptions.NoInlining)]
        public int AddNoInline(int a, int b) { return a + b; }
        // Patched from Lua for the *_patched cases.
        [MethodImpl(MethodImplOptions.NoInlining)]
        public int AddPatched(int a, int b) { return a + b; }
    }

    // Called from Lua by lua_object_arg, lua_instance_call and the string cases.
    public class Calls
    {
        public int Value = 1;
        static readonly string name = "hotfix-xlu";
        public static bool Echo(Calls o) { return o != null; }
        public int Get() { return Value; }
        public static int Len(string s) { return s.Length; }
        public static string Name() { return name; }
    }

    // A copy of the source generator's HotfixBridges slots (HotfixBridges.cs):
    // what an IntKey method calls at its entry.
    static class Slots
    {
        static readonly object sync = new object();
        internal static DelegateBridge[] slots = new DelegateBridge[0];

        internal static DelegateBridge Get(int id)
        {
            var s = slots;
            return (uint)id < (uint)s.Length ? s[id] : null;
        }

        internal static void Grow(int n)
        {
            lock (sync) slots = new DelegateBridge[n];
        }
    }

    // The entry checks written by hand, each in front of the same body, so
    // that one player compares them; the id is that of a method no patch set.
    public static class Checks
    {
        const int Id = 7;

#if (UNITY_IPHONE || UNITY_TVOS || UNITY_ANDROID) && !UNITY_EDITOR
        const string FlagsLibrary = "__Internal";
#else
        const string FlagsLibrary = "hotfixflags";
#endif
        // Assets/Plugins/iOS/HotfixFlags.cpp.
        [DllImport(FlagsLibrary, CallingConvention = CallingConvention.Cdecl, EntryPoint = "xlua_get_hotfix_flag")]
        static extern bool NativeFlag(int idx);

        [DllImport(FlagsLibrary, CallingConvention = CallingConvention.Cdecl, EntryPoint = "xlua_set_hotfix_flag")]
        internal static extern void SetNativeFlag(int idx, bool flag);

        static bool[] flags = new bool[64];

        static int Patched() { return -1; }

        [MethodImpl(MethodImplOptions.NoInlining)]
        public static int AddList(int a, int b)
        {
            if (HotfixDelegateBridge.xlua_get_hotfix_flag(Id)) return Patched();
            return a + b;
        }

        [MethodImpl(MethodImplOptions.NoInlining)]
        public static int AddNative(int a, int b)
        {
            if (NativeFlag(Id)) return Patched();
            return a + b;
        }

        [MethodImpl(MethodImplOptions.NoInlining)]
        public static int AddBoolArray(int a, int b)
        {
            if (flags[Id]) return Patched();
            return a + b;
        }

        [MethodImpl(MethodImplOptions.NoInlining)]
        public static int AddSlotCall(int a, int b)
        {
            var slot = Slots.Get(Id);
            if (slot != null) return Patched();
            return a + b;
        }

        [MethodImpl(MethodImplOptions.NoInlining)]
        public static int AddSlotInline(int a, int b)
        {
            var s = Slots.slots;
            var slot = (uint)Id < (uint)s.Length ? s[Id] : null;
            if (slot != null) return Patched();
            return a + b;
        }
    }

    public static class Bench
    {
        public static string Defines()
        {
            var d = new List<string>();
#if HOTFIX_ENABLE
            d.Add("HOTFIX_ENABLE");
#endif
#if THREAD_SAFE
            d.Add("THREAD_SAFE");
#endif
#if XLUA_BRIDGE_CHECKS
            d.Add("XLUA_BRIDGE_CHECKS");
#endif
            return d.Count == 0 ? "none" : string.Join(",", d.ToArray());
        }

        static int sink;

        static int LoopPlain(int n) { var o = new Plain(); int s = 0; for (int i = 0; i < n; i++) s += o.Add(i, 1); return s; }
        static int LoopPlainNoInline(int n) { var o = new Plain(); int s = 0; for (int i = 0; i < n; i++) s += o.AddNoInline(i, 1); return s; }
        static int LoopField(int n) { var o = new FieldMode(); int s = 0; for (int i = 0; i < n; i++) s += o.Add(i, 1); return s; }
        static int LoopFieldNoInline(int n) { var o = new FieldMode(); int s = 0; for (int i = 0; i < n; i++) s += o.AddNoInline(i, 1); return s; }
        static int LoopKey(int n) { var o = new KeyMode(); int s = 0; for (int i = 0; i < n; i++) s += o.Add(i, 1); return s; }
        static int LoopKeyNoInline(int n) { var o = new KeyMode(); int s = 0; for (int i = 0; i < n; i++) s += o.AddNoInline(i, 1); return s; }
        static int LoopList(int n) { int s = 0; for (int i = 0; i < n; i++) s += Checks.AddList(i, 1); return s; }
        static int LoopNative(int n) { int s = 0; for (int i = 0; i < n; i++) s += Checks.AddNative(i, 1); return s; }
        static int LoopBoolArray(int n) { int s = 0; for (int i = 0; i < n; i++) s += Checks.AddBoolArray(i, 1); return s; }
        static int LoopSlotCall(int n) { int s = 0; for (int i = 0; i < n; i++) s += Checks.AddSlotCall(i, 1); return s; }
        static int LoopSlotInline(int n) { int s = 0; for (int i = 0; i < n; i++) s += Checks.AddSlotInline(i, 1); return s; }

        static readonly object gate = new object();
        static int LoopLock(int n) { int s = 0; for (int i = 0; i < n; i++) { lock (gate) { s += i; } } return s; }

        // One case: the name, the calls per run and the loop.
        struct Case
        {
            public string Name;
            public int Calls;
            public Func<int, int> Loop;
            public Case(string name, int calls, Func<int, int> loop) { Name = name; Calls = calls; Loop = loop; }
        }

        static string Num(double v)
        {
            return v.ToString("0.###", CultureInfo.InvariantCulture);
        }

        static string Measure(Case c, int runs)
        {
            c.Loop(Math.Max(1, c.Calls / 10)); // warm up: JIT, class initialisation, caches
            var ns = new double[runs];
            for (int r = 0; r < runs; r++)
            {
                long start = Stopwatch.GetTimestamp();
                sink += c.Loop(c.Calls);
                ns[r] = (Stopwatch.GetTimestamp() - start) * (1e9 / Stopwatch.Frequency) / c.Calls;
            }
            var sorted = (double[])ns.Clone();
            Array.Sort(sorted);
            var all = new List<string>();
            foreach (double v in ns) all.Add(Num(v));
            return "XLUA_HOTFIX_BENCH {\"name\": \"" + c.Name + "\", \"calls\": " + c.Calls + ", \"median_ns\": " + Num(sorted[runs / 2])
                + ", \"min_ns\": " + Num(sorted[0]) + ", \"runs_ns\": [" + string.Join(", ", all.ToArray()) + "]}";
        }

        // Runs every case and hands each result line to log. idMapSource is the
        // text of the injector's id map (for intkey_patched), or null.
        // scale multiplies the calls per run.
        public static void Run(LuaEnv env, Action<string> log, string idMapSource, double scale, int runs)
        {
            int fast = (int)(10000000 * scale), slow = (int)(200000 * scale);
            var cases = new List<Case>
            {
                new Case("plain", fast, LoopPlain),
                new Case("plain_noinline", fast, LoopPlainNoInline),
                new Case("field", fast, LoopField),
                new Case("field_noinline", fast, LoopFieldNoInline),
                new Case("intkey", fast, LoopKey),
                new Case("intkey_noinline", fast, LoopKeyNoInline),
                new Case("check_list", fast, LoopList),
                new Case("check_bool_array", fast, LoopBoolArray),
                new Case("check_slot_call", fast, LoopSlotCall),
                new Case("check_slot_inline", fast, LoopSlotInline),
                new Case("lock_pair", fast, LoopLock),
            };
            bool native = false;
            try
            {
                Checks.SetNativeFlag(1, false);
                native = true;
            }
            catch (Exception e)
            {
                log("XLUA_HOTFIX_BENCH_SKIP check_native: " + e.GetType().Name + ": " + e.Message);
            }
            if (native) cases.Add(new Case("check_native", fast, LoopNative));

            var add = env.DoString("return function(a, b) return a + b end")[0] as LuaFunction;
            Func<int, int, int> f = add.Cast<Func<int, int, int>>();
            add.Dispose();
            cases.Add(new Case("delegate_call", slow * 5, n => { int s = 0; for (int i = 0; i < n; i++) s += f(i, 1); return s; }));
            var table = (LuaTable)env.DoString("local t = {} for i = 1, 64 do t[i] = i end return t")[0];
            cases.Add(new Case("table_get", slow * 5, n => { int s = 0; for (int i = 0; i < n; i++) s += table.Get<int, int>((i & 63) + 1); return s; }));
            Slots.Grow(16);
            var objectArg = (LuaFunction)env.DoString(@"
                local echo, o = CS.HotfixBench.Calls.Echo, CS.HotfixBench.Calls()
                return function(n) local s = 0 for i = 1, n do if echo(o) then s = s + 1 end end return s end")[0];
            cases.Add(new Case("lua_object_arg", slow * 5, n => Convert.ToInt32(objectArg.Call(n)[0])));
            var instanceCall = (LuaFunction)env.DoString(@"
                local o = CS.HotfixBench.Calls()
                return function(n) local s = 0 for i = 1, n do s = s + o:Get() end return s end")[0];
            cases.Add(new Case("lua_instance_call", slow * 5, n => Convert.ToInt32(instanceCall.Call(n)[0])));
            var stringArg = (LuaFunction)env.DoString(@"
                local len, s = CS.HotfixBench.Calls.Len, 'hello xlua'
                return function(n) local t = 0 for i = 1, n do t = t + len(s) end return t end")[0];
            cases.Add(new Case("lua_string_arg", slow * 5, n => Convert.ToInt32(stringArg.Call(n)[0])));
            var stringReturn = (LuaFunction)env.DoString(@"
                local name = CS.HotfixBench.Calls.Name
                return function(n) local t = 0 for i = 1, n do t = t + #name() end return t end")[0];
            cases.Add(new Case("lua_string_return", slow * 5, n => Convert.ToInt32(stringReturn.Call(n)[0])));

#if HOTFIX_ENABLE
            env.DoString("xlua.hotfix(CS.HotfixBench.FieldMode, 'AddPatched', function(self, a, b) return a + b + 1 end)");
            var patchedField = new FieldMode();
            if (patchedField.AddPatched(2, 3) != 6) throw new Exception("field_patched: the patch did not run");
            cases.Add(new Case("field_patched", slow, n => { int s = 0; for (int i = 0; i < n; i++) s += patchedField.AddPatched(i, 1); return s; }));
            if (idMapSource != null)
            {
                env.Global.Set("hotfix_bench_id_map", idMapSource);
                env.DoString(@"
                    local info = assert(load(hotfix_bench_id_map, '@hotfix_id_map'))()['HotfixBench.KeyMode']
                    CS.XLua.HotfixDelegateBridge.SetSlot(info['<assembly>'], info['AddPatched'][1], function(self, a, b) return a + b + 1 end)
                ");
                var patchedKey = new KeyMode();
                if (patchedKey.AddPatched(2, 3) != 6) throw new Exception("intkey_patched: the patch did not run");
                cases.Add(new Case("intkey_patched", slow, n => { int s = 0; for (int i = 0; i < n; i++) s += patchedKey.AddPatched(i, 1); return s; }));
            }
#endif
            log("XLUA_HOTFIX_BENCH_META {\"defines\": \"" + Defines() + "\", \"runtime\": \"" + RuntimeName() + "\", \"runs\": " + runs + "}");
            foreach (var c in cases) log(Measure(c, runs));
#if HOTFIX_ENABLE
            env.DoString("xlua.hotfix(CS.HotfixBench.FieldMode, 'AddPatched', nil)");
            if (idMapSource != null)
            {
                env.DoString(@"
                    local info = assert(load(hotfix_bench_id_map, '@hotfix_id_map'))()['HotfixBench.KeyMode']
                    CS.XLua.HotfixDelegateBridge.SetSlot(info['<assembly>'], info['AddPatched'][1], nil)
                ");
            }
#endif
            f = null;
            env.DoString("collectgarbage()");
            table.Dispose();
            objectArg.Dispose();
            instanceCall.Dispose();
            stringArg.Dispose();
            stringReturn.Dispose();
            log("XLUA_HOTFIX_BENCH_DONE " + sink);
        }

        static string RuntimeName()
        {
            var mono = Type.GetType("Mono.Runtime");
            if (mono != null)
            {
                var name = mono.GetMethod("GetDisplayName", System.Reflection.BindingFlags.NonPublic | System.Reflection.BindingFlags.Static);
                if (name != null) return "Mono " + name.Invoke(null, null);
            }
            return Environment.Version.ToString();
        }
    }

#if XLUA_GENERAL
    public static class Program
    {
        // HotfixBench.exe [--id-map FILE] [--scale X] [--runs N]
        public static int Main(string[] args)
        {
            string idMap = null;
            double scale = 1;
            int runs = 9;
            for (int i = 0; i + 1 < args.Length; i += 2)
            {
                switch (args[i])
                {
                    case "--id-map": idMap = System.IO.File.ReadAllText(args[i + 1]); break;
                    case "--scale": scale = double.Parse(args[i + 1], CultureInfo.InvariantCulture); break;
                    case "--runs": runs = int.Parse(args[i + 1]); break;
                    default: Console.WriteLine("unknown option " + args[i]); return 2;
                }
            }
            using (var env = new LuaEnv())
            {
                Bench.Run(env, Console.WriteLine, idMap, scale, runs);
                // The patches and the delegate are gone; their bridges must be collected before Dispose.
                GC.Collect();
                GC.WaitForPendingFinalizers();
                GC.Collect();
            }
            return 0;
        }
    }
#endif

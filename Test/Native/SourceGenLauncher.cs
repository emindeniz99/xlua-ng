using System;
using System.Collections;
using System.Collections.Generic;
using System.Linq;
using System.IO;
using System.Reflection;
using System.Text.RegularExpressions;
using System.Xml;
using XLua;

static class SourceGenLauncher
{
    static void Check(bool ok, string what)
    {
        if (!ok) throw new Exception("SourceGenLauncher: " + what);
    }

    static object Field(Type type, string name)
    {
        return type.GetField(name, BindingFlags.Static | BindingFlags.NonPublic).GetValue(null);
    }

    static bool structs(Assembly tests, string ns)
    {
        return tests.GetType(ns + ".Structs") != null && tests.GetType(ns + ".PackUnpack") != null;
    }

    static void Main()
    {
        Assembly tests = typeof(XLuaUnitTest).Assembly;
        var marker = tests.GetCustomAttributes(typeof(XLua.Binding.GeneratedBindingsAttribute), false)
            .Cast<XLua.Binding.GeneratedBindingsAttribute>().ToArray();
        Check(marker.Length == 1, "expected one [assembly: GeneratedBindings] in XLuaUnitTest, found " + marker.Length);
        Type bindings = marker[0].Bindings;
        Check(bindings.Assembly == tests && bindings.Name == "Bindings" && bindings.Namespace.StartsWith("XLua.Generated.XLuaUnitTest_")
            && !bindings.IsPublic && bindings.IsAbstract && bindings.IsSealed, "unexpected Bindings class " + bindings.FullName);
        Check(marker[0].ApiVersion == XLua.Binding.BindingApi.Version, "binding API version " + marker[0].ApiVersion);

        Type registry = typeof(LuaEnv).Assembly.GetType("XLua.Binding.BindingRegistry", true);
        var registered = (ICollection<string>)Field(registry, "registered");
        Check(registered.Count == 0, "something registered before the first LuaEnv");

        XLuaUnitTest.Main();

#if XLUA_SG_SKIP_REGISTER
        Check(registered.Count == 0 && !DelegateBridge.Gen_Flag, "a unit registered although XLUA_SG_SKIP_REGISTER is defined");
        Check(FallbackMember() == 15, "SourceGenFallback.Locked through reflection");
        Console.WriteLine("XLUA_SOURCE_GEN_CHECKS_PASS: nothing registered (XLUA_SG_SKIP_REGISTER); the suite ran through reflection and CodeEmit");
        return;
#else
        Check(registered.Contains("XLuaUnitTest"), "the first LuaEnv did not register XLuaUnitTest through GeneratedBindings");
        var names = (IDictionary)Field(registry, "names");
        foreach (DictionaryEntry e in names)
        {
            Check(((Type)e.Key).ToString() == (string)e.Value, "name table entry " + e.Value + " for " + e.Key);
        }
        foreach (var t in new[] { typeof(LuaTestObj), typeof(TestStruct), typeof(Action), typeof(Pedding) })
        {
            bool expected = t != typeof(Pedding); // Pedding has no configuration
            Check(names.Contains(t) == expected, t + (expected ? " is missing from" : " should not be in") + " the name table");
        }
        var loaders = (IDictionary)Field(registry, "loaders");
        foreach (var t in new[] { typeof(LuaTestObj), typeof(TestStruct), typeof(Coverage.Lazy), typeof(LuaTestType) })
        {
            Check(loaders.Contains(t), "no loader for " + t);
            var loader = (Delegate)loaders[t];
            Check(loader.Method.DeclaringType.Assembly == tests && loader.Method.DeclaringType.Namespace == bindings.Namespace
                && loader.Method.Name == "__Register", "the loader of " + t + " is " + loader.Method.DeclaringType.FullName + "." + loader.Method.Name);
        }
        Check(!loaders.Contains(typeof(Pedding)) && !loaders.Contains(typeof(Coverage.FilteredReflected)), "a loader for a type without configuration");
        Check(DelegateBridge.Gen_Flag, "DelegateBridge.Gen_Flag is not set by a unit with delegate bridges");

        var delegates = (IDictionary)Field(registry, "delegates");
        foreach (var t in new[] { typeof(Coverage.IntFunc), typeof(TestDelegate), typeof(Action), typeof(Coverage.ParamsCallback) })
        {
            Check(delegates.Contains(t), "no delegate bridge for " + t);
            var creator = (Delegate)delegates[t];
            Check(creator.Method.DeclaringType.Assembly == tests && creator.Method.DeclaringType.FullName.StartsWith(bindings.Namespace + "."),
                "the delegate creator of " + t + " is " + creator.Method.DeclaringType.FullName);
        }
        var interfaces = (IDictionary)Field(registry, "interfaceBridges");
        Check(interfaces.Contains(typeof(Coverage.IIndexed)) && interfaces.Contains(typeof(Upstream.IManyArgs)), "interface bridges missing");
        // GCOptimize (M4): struct and enum pushers, table casters and array accessors from this unit.
        var structTypes = (ICollection<Type>)Field(registry, "structTypes");
        var arrayGetters = (IDictionary)Field(registry, "arrayGetters");
        var arraySetters = (IDictionary)Field(registry, "arraySetters");
        foreach (var t in new[] { typeof(TestStruct), typeof(PackAsTableStruct), typeof(Gen6FloatStruct), typeof(LuaTestType), typeof(TableAutoTransSimpleClass) })
        {
            Check(structTypes.Contains(t), "no GCOptimize registration for " + t);
            Check(arraySetters.Contains(t.MakeArrayType()), "no array setter for " + t);
            Check(arrayGetters.Contains(t.MakeArrayType()) == t.IsValueType, (t.IsValueType ? "no" : "an") + " array getter for " + t);
        }
        Check(structs(tests, bindings.Namespace), "no generated Structs and PackUnpack classes");
        int bridgeMethods;
        // Not disposed: the delegates made here may still be alive (Mono scans the stack conservatively).
        var env = new LuaEnv();
        {
            var f = (LuaFunction)env.DoString("return function(x) return x * 2 end")[0];
            var listed = f.Cast<Coverage.IntFunc>();
            var unlisted = f.Cast<Unlisted>();
            Check(listed(21) == 42 && unlisted(21) == 42, "delegates of a Lua function");
            foreach (var d in new Delegate[] { listed, unlisted })
            {
                Check(d.Target is DelegateBridge && d.Method.IsStatic && d.Method.DeclaringType.FullName == bindings.Namespace + ".Bridges",
                    d.GetType() + " uses " + d.Method.DeclaringType + "." + d.Method.Name);
            }
            Check(listed.Method == unlisted.Method, "an unconfigured delegate type with the same signature takes the configured one's bridge");
            bridgeMethods = listed.Method.DeclaringType.GetMethods(BindingFlags.Static | BindingFlags.NonPublic).Count(m => m.Name.StartsWith("__Gen_Delegate_Imp"));

            var t = (LuaTable)env.DoString("return { Count = 3, Sum = function(self, ...) local s = 0 for _, v in ipairs({...}) do s = s + v end return s end }")[0];
            var indexed = t.Cast<Coverage.IIndexed>();
            Check(indexed.GetType().Assembly == tests && indexed.GetType().Namespace == bindings.Namespace, "the IIndexed bridge is " + indexed.GetType().FullName);
            Check(indexed.Count == 3 && indexed.Sum(1, 2, 3) == 6, "the IIndexed bridge calls Lua");

            // A GCOptimize struct made, read and passed back from Lua allocates
            // no managed memory per value (it was boxed before M4: 32 bytes).
            var counter = typeof(GC).GetMethod("GetAllocatedBytesForCurrentThread", Type.EmptyTypes);
            if (counter != null)
            {
                var loop = (LuaFunction)env.DoString("local S = CS.TestStruct\nreturn function(n) local s = 0 for i = 1, n do local v = S(i, 2) s = s + v.a + v.b end return s end")[0];
                loop.Call(100);
                long before = (long)counter.Invoke(null, null);
                loop.Call(5000);
                long bytes = (long)counter.Invoke(null, null) - before;
                Check(bytes < 5000, "a GCOptimize struct through the generated wrappers allocated " + bytes + " managed bytes for 5000 values");
                Console.WriteLine("XLUA_SOURCE_GEN_STRUCT_ALLOC: " + bytes + " managed bytes for 5000 TestStruct values");
            }
            StringAllocations(env);
        }
        StringThreads(4, 3000);

        // The wrapper functions of LuaTestObj: native callbacks, or with
        // GEN_CODE_MINIMIZE (run_managed.py --source-gen --gen-code-minimize)
        // extension methods of the translator in its CSharpWrapper table,
        // called through the native trampoline.
        Type wrapperClass = ((Delegate)loaders[typeof(LuaTestObj)]).Method.DeclaringType;
        var functions = wrapperClass.GetMethods(BindingFlags.Static | BindingFlags.Public | BindingFlags.NonPublic).Where(m => m.Name != "__Register").ToArray();
        Check(functions.Length > 0, "no wrapper functions in " + wrapperClass);
        foreach (var f in functions)
        {
            var ps = f.GetParameters();
#if GEN_CODE_MINIMIZE
            Check(ps.Length == 3 && ps[0].ParameterType == typeof(ObjectTranslator) && ps[1].ParameterType == typeof(IntPtr) && ps[2].ParameterType == typeof(int)
                && !f.IsDefined(typeof(MonoPInvokeCallbackAttribute), false) && f.IsPrivate, "not a GCM wrapper function: " + f);
#else
            Check(ps.Length == 1 && ps[0].ParameterType == typeof(IntPtr) && f.IsDefined(typeof(MonoPInvokeCallbackAttribute), false), "not a native callback: " + f);
#endif
        }
#if GEN_CODE_MINIMIZE
        {
            var translatorField = typeof(LuaEnv).GetField("translator", BindingFlags.Instance | BindingFlags.NonPublic);
            var sizeField = typeof(ObjectTranslator).GetField("csharpWrapperSize", BindingFlags.Instance | BindingFlags.NonPublic);
            var gcmEnv = new LuaEnv();
            var translator = translatorField.GetValue(gcmEnv);
            int before = (int)sizeField.GetValue(translator);
            gcmEnv.DoString("local o = CS.LuaTestObj() o.testVar = 3");
            int added = (int)sizeField.GetValue(translator) - before;
            Check(added >= functions.Length, "LuaTestObj's registration added " + added + " CSharpWrapper entries for " + functions.Length + " functions");
            Console.WriteLine("XLUA_SOURCE_GEN_GCM: " + functions.Length + " GCM functions in " + wrapperClass.Name + "; its registration added " + added + " CSharpWrapper entries");
        }
#endif

        // Per-member fallback (M5): the init-only setter goes through
        // BindingApi.RegisterFallback, works, and logs its reason once.
        var console = Console.Out;
        var captured = new StringWriter();
        Console.SetOut(captured);
        int locked;
        try
        {
            locked = FallbackMember();
        }
        finally
        {
            Console.SetOut(console);
        }
        Check(locked == 15, "SourceGenFallback.Locked through the fallback gave " + locked);
        int logs = Regex.Matches(captured.ToString(), Regex.Escape("SourceGenFallback.Locked is reached through reflection")).Count;
        Check(logs == 1, "the fallback of SourceGenFallback.Locked logged " + logs + " times: " + captured);

        int linkEntries = CheckLinkXml(tests, bindings.Namespace);
        Console.WriteLine("XLUA_SOURCE_GEN_CHECKS_PASS: " + bindings.FullName + " registered " + names.Count + " names, "
            + loaders.Count + " wrappers, " + delegates.Count + " delegate types on " + bridgeMethods + " bridges and "
            + interfaces.Count + " interface bridges; link.xml has " + linkEntries + " entries");
#endif
    }

    // Strings through the generated wrappers allocate only the string C#
    // gets: a push into Lua nothing, a read from Lua the new string. Short
    // strings go through a buffer that the bridge keeps, shared without
    // THREAD_SAFE and HOTFIX_ENABLE and one per thread with them (a new
    // array per string before 2026-10-28).
    static void StringAllocations(LuaEnv env)
    {
        var counter = typeof(GC).GetMethod("GetAllocatedBytesForCurrentThread", Type.EmptyTypes);
        if (counter == null) return;
        const int n = 2000;
        var o = new TestChineseString();
        var push = (LuaFunction)env.DoString("return function(o, n) local s = 0 for i = 1, n do s = s + #o.short_simple_string end return s end")[0];
        var read = (LuaFunction)env.DoString("return function(o, n, v) for i = 1, n do o.short_simple_string = v end end")[0];
        push.Call(o, 10);
        read.Call(o, 10, o.short_simple_string);
        long before = (long)counter.Invoke(null, null);
        push.Call(o, n);
        long pushed = (long)counter.Invoke(null, null) - before;

        // What the strings themselves take: the same decode, n times, in C#.
        byte[] utf8 = System.Text.Encoding.UTF8.GetBytes(o.short_simple_string);
        string[] made = new string[n];
        System.Text.Encoding.UTF8.GetString(utf8);
        before = (long)counter.Invoke(null, null);
        for (int i = 0; i < n; i++) made[i] = System.Text.Encoding.UTF8.GetString(utf8);
        long strings = (long)counter.Invoke(null, null) - before;

        before = (long)counter.Invoke(null, null);
        read.Call(o, n, o.short_simple_string);
        long readBytes = (long)counter.Invoke(null, null) - before;
        Check(pushed < n, "pushing a C# string into Lua allocated " + pushed + " managed bytes for " + n + " strings");
        Check(readBytes < strings + n, "reading a Lua string allocated " + readBytes + " managed bytes for " + n
            + " strings, which take " + strings);
        Console.WriteLine("XLUA_SOURCE_GEN_STRING_ALLOC: " + pushed + " managed bytes for " + n + " pushes, " + readBytes
            + " for " + n + " reads (the strings take " + strings + ")");
    }

    // Strings pushed and read on several threads, an env each, which run at
    // the same time under THREAD_SAFE and HOTFIX_ENABLE (one after another
    // without them): each thread's strings must come back unchanged while the
    // others encode and decode theirs. Short ASCII, non-ASCII and strings
    // longer than the bridge's 256-byte buffer.
    static void StringThreads(int threads, int iterations)
    {
        var results = new string[threads];
        var workers = new System.Threading.Thread[threads];
        var go = new System.Threading.ManualResetEvent(false);
        for (int i = 0; i < threads; i++)
        {
            int k = i;
            workers[i] = new System.Threading.Thread(() =>
            {
                var errors = new System.Text.StringBuilder();
                var env = new LuaEnv();
                try
                {
                    var f = (LuaFunction)env.DoString("return function(o, s) o.short_simple_string = s return o.short_simple_string, s .. '!' end")[0];
                    var o = new TestChineseString();
                    string[] bases = { "t" + k + "-", "线程" + k + "é-", new string((char)('a' + k), 300) + "é" };
                    go.WaitOne();
                    for (int j = 0; j < iterations && errors.Length < 400; j++)
                    {
                        string s = bases[j % bases.Length] + j;
                        object[] r = f.Call(o, s);
                        if (o.short_simple_string != s) errors.Append("C# read " + o.short_simple_string + " for " + s + "; ");
                        if (r.Length != 2 || (string)r[0] != s || (string)r[1] != s + "!")
                            errors.Append("Lua returned " + string.Join(",", r.Select(x => "" + x).ToArray()) + " for " + s + "; ");
                    }
                    f.Dispose();
                }
                catch (Exception e)
                {
                    errors.Append(e.GetType().Name + ": " + e.Message + "; ");
                }
                finally
                {
                    env.Dispose();
                }
                results[k] = errors.Length == 0 ? "" : "thread " + k + ": " + errors;
            });
            workers[i].IsBackground = true;
        }
        string hung = "";
#if THREAD_SAFE || HOTFIX_ENABLE
        for (int i = 0; i < threads; i++) workers[i].Start();
        go.Set();
        for (int i = 0; i < threads; i++)
        {
            if (!workers[i].Join(60000)) hung += "thread " + i + " did not finish in 60 s; ";
        }
#else
        go.Set();
        for (int i = 0; i < threads; i++)
        {
            workers[i].Start();
            if (!workers[i].Join(60000)) hung += "thread " + i + " did not finish in 60 s; ";
        }
#endif
        string failed = string.Join("", results) + hung;
        Check(failed == "", "strings on " + threads + " threads: " + failed);
        Console.WriteLine("XLUA_SOURCE_GEN_STRING_THREADS: " + threads + " threads, " + iterations + " strings each"
#if THREAD_SAFE || HOTFIX_ENABLE
            + ", at the same time");
#else
            + ", one thread after another");
#endif
    }

    // Sets the init-only property twice from Lua, in a LuaEnv of its own.
    static int FallbackMember()
    {
        var env = new LuaEnv();
        var r = env.DoString("local o = CS.SourceGenFallback() o.Locked = 7 local a = o.Locked o.Locked = 8 return a + o.Locked")[0];
        return Convert.ToInt32(r);
    }

    // The link.xml fragment against what the wrappers reach by reflection: every
    // lazy and fallback member of the manifest that its type declares, and every
    // [ReflectionUse] type of the suite (preserve="all"). Returns the number of
    // members and types it lists.
    static int CheckLinkXml(Assembly tests, string ns)
    {
        var holder = tests.GetType(ns + ".LinkXml", true);
        var xml = (string)holder.GetField("Xml", BindingFlags.Static | BindingFlags.NonPublic).GetRawConstantValue();
        var doc = new XmlDocument();
        doc.LoadXml(xml);
        var listed = new HashSet<string>();
        int entries = 0;
        foreach (XmlElement a in doc.DocumentElement.SelectNodes("assembly"))
        {
            foreach (XmlElement t in a.SelectNodes("type"))
            {
                string key = a.GetAttribute("fullname") + "|" + t.GetAttribute("fullname");
                if (t.GetAttribute("preserve") == "all")
                {
                    listed.Add(key + "|*");
                    entries++;
                }
                foreach (XmlElement m in t.ChildNodes.OfType<XmlElement>())
                {
                    listed.Add(key + "|" + m.Name + "|" + m.GetAttribute("name"));
                    entries++;
                }
            }
        }
        var manifest = (string)tests.GetType(ns + ".Manifest", true).GetField("Json", BindingFlags.Static | BindingFlags.NonPublic).GetRawConstantValue();
        int lazy = 0;
        foreach (Match m in Regex.Matches(manifest, "\\{\"type\":\"([^\"]+)\",\"kind\":\"class\".*?\"lazy\":\\[([^\\]]*)\\],\"fallback\":\\[([^\\]]*)\\]"))
        {
            Type type = FindType(m.Groups[1].Value);
            if (type == null) continue; // a constructed generic type: Assembly.GetType does not take its name
            foreach (Match e in Regex.Matches(m.Groups[2].Value + "," + m.Groups[3].Value, "\"[A-Z_]+ (\\S+) (\\w+)"))
            {
                string name = e.Groups[1].Value, kind = e.Groups[2].Value;
                var declared = type.GetMember(name, BindingFlags.Public | BindingFlags.Instance | BindingFlags.Static | BindingFlags.DeclaredOnly);
                string element = kind == "Method" ? "method" : kind.StartsWith("Field") ? "field" : kind.StartsWith("Property") ? "property" : "event";
                bool declares = declared.Any(d => element == "method" ? d is MethodBase : element == "field" ? d is FieldInfo
                    : element == "property" ? d is PropertyInfo : d is EventInfo);
                if (!declares) continue; // an extension method, kept through the extension method map
                string key = type.Assembly.GetName().Name + "|" + type.FullName.Replace('+', '/');
                Check(listed.Contains(key + "|" + element + "|" + name) || listed.Contains(key + "|*"), "link.xml does not keep " + type + "." + name);
                lazy++;
            }
        }
        Check(lazy > 0, "the manifest lists no lazy members");
        int reflectionUse = 0;
        foreach (var type in tests.GetTypes().Where(t => t.IsDefined(typeof(ReflectionUseAttribute), false)))
        {
            Check(listed.Contains(type.Assembly.GetName().Name + "|" + type.FullName.Replace('+', '/') + "|*"), "link.xml does not keep [ReflectionUse] " + type);
            reflectionUse++;
        }
        Check(reflectionUse > 0, "the suite has no [ReflectionUse] types");
        Console.WriteLine("XLUA_SOURCE_GEN_LINKXML: " + lazy + " lazy members and " + reflectionUse + " [ReflectionUse] types kept");
        return entries;
    }

    static Type FindType(string name)
    {
        foreach (var assembly in AppDomain.CurrentDomain.GetAssemblies())
        {
            var t = assembly.GetType(name, false);
            if (t != null) return t;
        }
        return null;
    }
}

// Not configured: it gets the bridge of Coverage.IntFunc, which has the same signature.
public delegate int Unlisted(int x);

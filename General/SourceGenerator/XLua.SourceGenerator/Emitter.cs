// Writes the generated C#: C# 9 syntax only (Unity's default -langversion:9),
// every type qualified with global::, output sorted so that the same input
// gives byte-identical files (section 5.1).
using System.Collections.Generic;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;

namespace XLua.SourceGenerator
{
    internal static class Emitter
    {
        public const string BindingsFile = "XLua.Bindings.g.cs";

        public static void Emit(SourceProductionContext spc, AssemblyInfo assembly, EquatableArray<ConfigEntry> entries)
        {
            if (assembly.BindingApiVersion == null) return; // XLua is not referenced: nothing to do
            if (assembly.BindingApiVersion != XLuaBindingGenerator.ApiVersion)
            {
                spc.ReportDiagnostic(Diagnostic.Create(Diagnostics.ApiVersion, Location.None,
                    XLuaBindingGenerator.ApiVersion, assembly.BindingApiVersion));
                return;
            }

            Report(spc, assembly, entries);

            // The name table: every configured type once, by Lua name.
            var named = new SortedDictionary<string, string>(System.StringComparer.Ordinal); // typeof -> Lua name
            foreach (var e in entries)
            {
                if (e.Named && !named.ContainsKey(e.TypeofExpr)) named.Add(e.TypeofExpr, e.LuaName);
            }
            if (named.Count == 0) return;

            spc.AddSource(BindingsFile, SourceText.From(Bindings(assembly, named), Encoding.UTF8));
        }

        static void Report(SourceProductionContext spc, AssemblyInfo assembly, EquatableArray<ConfigEntry> entries)
        {
            var gcFlags = new Dictionary<string, ConfigEntry>();
            foreach (var e in entries.OrderBy(x => x.Path, System.StringComparer.Ordinal).ThenBy(x => x.Span.Start))
            {
                Location where = e.GetLocation();
                string attribute = e.Kind.ToString();
                switch (e.Problem)
                {
                    case TypeProblem.Open:
                        spc.ReportDiagnostic(Diagnostic.Create(Diagnostics.GenericType, where, attribute, e.DisplayName,
                            e.Kind == ConfigKind.Hotfix ? "built on a generic type definition" : "an open generic type"));
                        break;
                    case TypeProblem.ClosedGeneric:
                        spc.ReportDiagnostic(Diagnostic.Create(Diagnostics.GenericType, where, attribute, e.DisplayName,
                            "a constructed generic type (Hotfix takes the generic type definition)"));
                        break;
                    case TypeProblem.NotAccessible:
                        spc.ReportDiagnostic(Diagnostic.Create(Diagnostics.NotAccessible, where, attribute, e.DisplayName, assembly.Name));
                        break;
                    case TypeProblem.NotDelegateOrInterface:
                        spc.ReportDiagnostic(Diagnostic.Create(Diagnostics.NotDelegateOrInterface, where, e.DisplayName));
                        break;
                    case TypeProblem.OtherAssembly:
                        spc.ReportDiagnostic(Diagnostic.Create(Diagnostics.HotfixOtherAssembly, where, e.DisplayName, e.DefiningAssembly));
                        break;
                }
                if (e.MissingMembers != null)
                {
                    var descriptor = e.Form == ConfigForm.ByName ? Diagnostics.NoSuchMemberByName : Diagnostics.NoSuchMember;
                    spc.ReportDiagnostic(Diagnostic.Create(descriptor, where, attribute, e.MissingMembers, e.DisplayName));
                }
                if (e.Form == ConfigForm.List)
                {
                    spc.ReportDiagnostic(Diagnostic.Create(Diagnostics.ConfigurationList, where, attribute, e.DisplayName));
                }
                if (e.Kind == ConfigKind.GCOptimize && e.Problem == TypeProblem.None && e.TypeofExpr != null)
                {
                    ConfigEntry first;
                    if (!gcFlags.TryGetValue(e.TypeofExpr, out first)) gcFlags.Add(e.TypeofExpr, e);
                    else if (first.Flags != e.Flags)
                        spc.ReportDiagnostic(Diagnostic.Create(Diagnostics.ConflictingGCOptimize, where, e.DisplayName,
                            OptimizeFlags(e.Flags), OptimizeFlags(first.Flags)));
                }
            }
        }

        static string OptimizeFlags(int flags)
        {
            return flags == 0 ? "Default" : flags == 1 ? "PackAsTable" : flags.ToString();
        }

        static string Bindings(AssemblyInfo assembly, SortedDictionary<string, string> named)
        {
            string ns = Names.GeneratedNamespace(assembly.Name);
            var sb = new StringBuilder();
            sb.Append("// <auto-generated/>\n");
            sb.Append("// xLua source generator: the registration of assembly ").Append(assembly.Name).Append(".\n");
            sb.Append("// No wrappers are generated yet; Lua reaches the types below through reflection.\n");
            sb.Append("#nullable disable\n\n");
            sb.Append("[assembly: global::XLua.Binding.GeneratedBindings(typeof(global::").Append(ns)
              .Append(".Bindings), global::XLua.Binding.BindingApi.Version)]\n\n");
            sb.Append("namespace ").Append(ns).Append("\n{\n");
            if (assembly.HasPreserve) sb.Append("    [global::UnityEngine.Scripting.Preserve]\n");
            sb.Append("    internal static class Bindings\n    {\n");
            sb.Append("        internal const string AssemblyName = ").Append(Names.Literal(assembly.Name)).Append(";\n\n");
            if (assembly.HasRuntimeInitialize)
            {
                sb.Append("        [global::UnityEngine.RuntimeInitializeOnLoadMethod(global::UnityEngine.RuntimeInitializeLoadType.SubsystemRegistration)]\n");
            }
            if (assembly.HasPreserve) sb.Append("        [global::UnityEngine.Scripting.Preserve]\n");
            sb.Append("        internal static void Register()\n        {\n");
            sb.Append("            var b = new global::XLua.Binding.AssemblyBindings(AssemblyName, global::XLua.Binding.BindingApi.Version);\n");
            foreach (var kv in named.OrderBy(kv => kv.Value, System.StringComparer.Ordinal).ThenBy(kv => kv.Key, System.StringComparer.Ordinal))
            {
                sb.Append("            b.Name(typeof(").Append(kv.Key).Append("), ").Append(Names.Literal(kv.Value)).Append(");\n");
            }
            sb.Append("            global::XLua.Binding.BindingApi.Register(b);\n");
            sb.Append("        }\n");
            if (assembly.HasEditorInitialize)
            {
                sb.Append("\n#if UNITY_EDITOR\n");
                sb.Append("        // Edit-mode code and tests run without entering play mode.\n");
                sb.Append("        [global::UnityEditor.InitializeOnLoadMethod]\n");
                sb.Append("        static void EditorRegister()\n        {\n            Register();\n        }\n");
                sb.Append("#endif\n");
            }
            sb.Append("    }\n}\n");
            return sb.ToString();
        }
    }
}

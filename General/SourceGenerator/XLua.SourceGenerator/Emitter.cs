// Writes the generated C#: C# 9 syntax only (Unity's default -langversion:9),
// every type qualified with global::, output sorted so that the same input
// gives byte-identical files (section 5.1).
using System.Collections.Generic;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;

namespace XLua.SourceGenerator
{
    internal static class Emitter
    {
        public const string BindingsFile = "XLua.Bindings.g.cs";
        public const string BridgesFile = "XLua.Bridges.g.cs";
        public const string StructsFile = "XLua.Structs.g.cs";
        public const string PackFile = "XLua.PackUnpack.g.cs";
        public const string ManifestFile = "XLua.Manifest.g.cs";

        // One wrapper class or interface bridge per type, in its own file (section 5.1).
        public static void EmitWrapper(SourceProductionContext spc, TypeModel model, AssemblyInfo assembly)
        {
            if (assembly.BindingApiVersion != XLuaBindingGenerator.ApiVersion) return;
            var sb = new StringBuilder();
            sb.Append("// <auto-generated/>\n");
            sb.Append(model.ClassName.StartsWith("B_") ? "// xLua source generator: the interface bridge of " : "// xLua source generator: the Lua wrapper of ")
              .Append(model.LuaName).Append(".\n");
            sb.Append("#nullable disable\n");
            sb.Append("#pragma warning disable CS0618, CS0612 // [Obsolete] members without error stay visible outside Unity, as with the legacy generator\n\n");
            sb.Append("namespace ").Append(Names.GeneratedNamespace(assembly.Name)).Append("\n{\n");
            sb.Append(model.Source);
            sb.Append("}\n");
            spc.AddSource(model.HintName, SourceText.From(sb.ToString(), Encoding.UTF8));
        }

        public static void Emit(SourceProductionContext spc, AssemblyInfo assembly, EquatableArray<ConfigEntry> entries, WrapperSet wrappers)
        {
            if (assembly.BindingApiVersion == null) return; // XLua is not referenced: nothing to do
            if (assembly.BindingApiVersion != XLuaBindingGenerator.ApiVersion)
            {
                spc.ReportDiagnostic(Diagnostic.Create(Diagnostics.ApiVersion, Location.None,
                    XLuaBindingGenerator.ApiVersion, assembly.BindingApiVersion));
                return;
            }

            Report(spc, assembly, entries);

            // The name table: every configured type once, by Lua name.
            var named = new SortedDictionary<string, string>(System.StringComparer.Ordinal); // typeof -> Lua name
            foreach (var e in entries)
            {
                if (e.Named && !named.ContainsKey(e.TypeofExpr)) named.Add(e.TypeofExpr, e.LuaName);
            }
            if (named.Count == 0 && wrappers.Types.Length == 0) return;

            if (wrappers.BoundElsewhere.Length > 0)
            {
                foreach (var line in wrappers.BoundElsewhere.Split('\n'))
                {
                    var parts = line.Split('|');
                    spc.ReportDiagnostic(Diagnostic.Create(Diagnostics.BoundElsewhere, Location.None, parts[0], parts[1]));
                }
            }
            if (wrappers.NotWrapped.Length > 0)
            {
                foreach (var line in wrappers.NotWrapped.Split('\n'))
                {
                    var parts = line.Split('|');
                    spc.ReportDiagnostic(Diagnostic.Create(Diagnostics.TypeNotWrapped, Location.None, parts[0], parts[1]));
                }
            }
            foreach (var t in wrappers.Types)
            {
                if (string.IsNullOrEmpty(t.Dropped)) continue;
                foreach (var line in t.Dropped.Split('\n'))
                {
                    spc.ReportDiagnostic(Diagnostic.Create(Diagnostics.MemberDropped, Location.None, t.LuaName, line));
                }
            }
            if (wrappers.NotPackable.Length > 0)
            {
                foreach (var line in wrappers.NotPackable.Split('\n'))
                {
                    spc.ReportDiagnostic(Diagnostic.Create(Diagnostics.NotPackable, Location.None, line));
                }
            }
            spc.AddSource(BindingsFile, SourceText.From(Bindings(assembly, named, wrappers), Encoding.UTF8));
            if (wrappers.DelegateBridges.Length > 0) spc.AddSource(BridgesFile, SourceText.From(Bridges(assembly, wrappers), Encoding.UTF8));
            if (wrappers.StructsSource.Length > 0)
            {
                spc.AddSource(StructsFile, SourceText.From(Class(assembly, "Structs", "the GCOptimize push, get and update", wrappers.StructsSource), Encoding.UTF8));
            }
            if (wrappers.PackSource.Length > 0)
            {
                spc.AddSource(PackFile, SourceText.From(Class(assembly, "PackUnpack", "the GCOptimize struct packing", wrappers.PackSource), Encoding.UTF8));
            }
            spc.AddSource(ManifestFile, SourceText.From(Manifest(assembly, wrappers), Encoding.UTF8));
        }

        // An internal static class of the generated namespace with the given members.
        static string Class(AssemblyInfo assembly, string name, string what, string members)
        {
            var sb = new StringBuilder();
            sb.Append("// <auto-generated/>\n");
            sb.Append("// xLua source generator: ").Append(what).Append(" of assembly ").Append(assembly.Name).Append(".\n");
            sb.Append("#nullable disable\n");
            sb.Append("#pragma warning disable CS0618, CS0612\n\n");
            sb.Append("namespace ").Append(Names.GeneratedNamespace(assembly.Name)).Append("\n{\n");
            sb.Append("    internal static class ").Append(name).Append("\n    {\n");
            sb.Append(members);
            sb.Append("    }\n}\n");
            return sb.ToString();
        }

        // The delegate bridges (Bridges.cs): static methods closed over a Lua
        // function's DelegateBridge by the delegates Bindings registers.
        static string Bridges(AssemblyInfo assembly, WrapperSet wrappers)
        {
            var sb = new StringBuilder();
            sb.Append("// <auto-generated/>\n");
            sb.Append("// xLua source generator: the delegate bridges of assembly ").Append(assembly.Name).Append(".\n");
            sb.Append("#nullable disable\n");
            sb.Append("#pragma warning disable CS0618, CS0612\n");
            sb.Append(wrappers.DelegatePragmas).Append('\n');
            sb.Append("namespace ").Append(Names.GeneratedNamespace(assembly.Name)).Append("\n{\n");
            sb.Append("    internal static class Bridges\n    {");
            sb.Append(wrappers.DelegateBridges);
            sb.Append("    }\n}\n");
            return sb.ToString();
        }

        // The binding surface as JSON (section 2 row 12): for the LuaCATS
        // definitions (M10) and the comparison with the legacy generator
        // (Test/Native/surface_diff.py). Only Editor and host builds keep it.
        static string Manifest(AssemblyInfo assembly, WrapperSet wrappers)
        {
            var json = new Json();
            json.BeginObject();
            json.Key("generator").Value("source");
            json.Key("types").BeginArray();
            foreach (var t in wrappers.Types) json.Raw(t.Manifest);
            json.EndArray();
            json.Key("extensionMethods").Raw(wrappers.ExtensionManifest);
            json.Key("structs").Raw(wrappers.StructManifest);
            json.Key("packUnpack").Raw(wrappers.PackManifest);
            json.Key("delegateBridges").Raw(wrappers.DelegateManifest);
            json.Key("interfaceBridges").Raw(wrappers.InterfaceManifest);
            json.EndObject();
            var sb = new StringBuilder();
            sb.Append("// <auto-generated/>\n#nullable disable\n#if UNITY_EDITOR || XLUA_GENERAL\n");
            sb.Append("namespace ").Append(Names.GeneratedNamespace(assembly.Name)).Append("\n{\n");
            sb.Append("    internal static class Manifest\n    {\n");
            sb.Append("        internal const string Json = @\"").Append(json.ToString().Replace("\"", "\"\"")).Append("\";\n");
            sb.Append("    }\n}\n#endif\n");
            return sb.ToString();
        }

        static void Report(SourceProductionContext spc, AssemblyInfo assembly, EquatableArray<ConfigEntry> entries)
        {
            var gcFlags = new Dictionary<string, ConfigEntry>();
            foreach (var e in entries.OrderBy(x => x.Path, System.StringComparer.Ordinal).ThenBy(x => x.Span.Start))
            {
                Location where = e.GetLocation();
                string attribute = e.Kind.ToString();
                switch (e.Problem)
                {
                    case TypeProblem.Open:
                        spc.ReportDiagnostic(Diagnostic.Create(Diagnostics.GenericType, where, attribute, e.DisplayName,
                            e.Kind == ConfigKind.Hotfix ? "built on a generic type definition" : "an open generic type"));
                        break;
                    case TypeProblem.ClosedGeneric:
                        spc.ReportDiagnostic(Diagnostic.Create(Diagnostics.GenericType, where, attribute, e.DisplayName,
                            "a constructed generic type (Hotfix takes the generic type definition)"));
                        break;
                    case TypeProblem.NotAccessible:
                        spc.ReportDiagnostic(Diagnostic.Create(Diagnostics.NotAccessible, where, attribute, e.DisplayName, assembly.Name));
                        break;
                    case TypeProblem.NotDelegateOrInterface:
                        spc.ReportDiagnostic(Diagnostic.Create(Diagnostics.NotDelegateOrInterface, where, e.DisplayName));
                        break;
                    case TypeProblem.OtherAssembly:
                        spc.ReportDiagnostic(Diagnostic.Create(Diagnostics.HotfixOtherAssembly, where, e.DisplayName, e.DefiningAssembly));
                        break;
                }
                if (e.MissingMembers != null)
                {
                    var descriptor = e.Form == ConfigForm.ByName ? Diagnostics.NoSuchMemberByName : Diagnostics.NoSuchMember;
                    spc.ReportDiagnostic(Diagnostic.Create(descriptor, where, attribute, e.MissingMembers, e.DisplayName));
                }
                if (e.Form == ConfigForm.List)
                {
                    spc.ReportDiagnostic(Diagnostic.Create(Diagnostics.ConfigurationList, where, attribute, e.DisplayName));
                }
                if (e.Kind == ConfigKind.GCOptimize && e.Problem == TypeProblem.None && e.TypeofExpr != null)
                {
                    ConfigEntry first;
                    if (!gcFlags.TryGetValue(e.TypeofExpr, out first)) gcFlags.Add(e.TypeofExpr, e);
                    else if (first.Flags != e.Flags)
                        spc.ReportDiagnostic(Diagnostic.Create(Diagnostics.ConflictingGCOptimize, where, e.DisplayName,
                            OptimizeFlags(e.Flags), OptimizeFlags(first.Flags)));
                }
            }
        }

        static string OptimizeFlags(int flags)
        {
            return flags == 0 ? "Default" : flags == 1 ? "PackAsTable" : flags.ToString();
        }

        static string Bindings(AssemblyInfo assembly, SortedDictionary<string, string> named, WrapperSet wrappers)
        {
            string ns = Names.GeneratedNamespace(assembly.Name);
            var sb = new StringBuilder();
            sb.Append("// <auto-generated/>\n");
            sb.Append("// xLua source generator: the registration of assembly ").Append(assembly.Name).Append(".\n");
            sb.Append("#nullable disable\n");
            sb.Append("#pragma warning disable CS0618, CS0612\n\n");
            sb.Append("[assembly: global::XLua.Binding.GeneratedBindings(typeof(global::").Append(ns)
              .Append(".Bindings), global::XLua.Binding.BindingApi.Version, new global::System.Type[] {");
            foreach (var t in wrappers.Types) sb.Append("\n    typeof(").Append(t.TypeofExpr).Append("),");
            sb.Append(wrappers.Types.Length > 0 ? "\n" : " ").Append("})]\n\n");
            sb.Append("namespace ").Append(ns).Append("\n{\n");
            if (assembly.HasPreserve) sb.Append("    [global::UnityEngine.Scripting.Preserve]\n");
            sb.Append("    internal static class Bindings\n    {\n");
            sb.Append("        internal const string AssemblyName = ").Append(Names.Literal(assembly.Name)).Append(";\n\n");
            if (wrappers.ExtensionDelegates.Length > 0)
            {
                sb.Append("        // The extension methods of the map (InternalGlobals.extensionMethodMap), taken from delegates, not by name.\n");
                sb.Append(wrappers.ExtensionDelegates).Append('\n');
            }
            if (assembly.HasRuntimeInitialize)
            {
                sb.Append("        [global::UnityEngine.RuntimeInitializeOnLoadMethod(global::UnityEngine.RuntimeInitializeLoadType.SubsystemRegistration)]\n");
            }
            if (assembly.HasPreserve) sb.Append("        [global::UnityEngine.Scripting.Preserve]\n");
            sb.Append("        internal static void Register()\n        {\n");
            sb.Append("            var b = new global::XLua.Binding.AssemblyBindings(AssemblyName, global::XLua.Binding.BindingApi.Version);\n");
            var wrapped = new HashSet<string>();
            foreach (var t in wrappers.Types)
            {
                wrapped.Add(t.TypeofExpr);
                sb.Append("            b.Type(typeof(").Append(t.TypeofExpr).Append("), ").Append(Names.Literal(t.LuaName)).Append(", ")
                  .Append(t.ClassName).Append(".__Register);\n");
            }
            // [CSharpCallLua]: delegates closed over the bridge (Bridges), interface bridges.
            sb.Append(wrappers.DelegateRegistration);
            // GCOptimize: push, get and update per LuaEnv, table casters, array element access (Structs).
            sb.Append(wrappers.StructRegistration);
            foreach (var t in wrappers.Interfaces)
            {
                sb.Append("            b.InterfaceBridge(typeof(").Append(t.TypeofExpr).Append("), ").Append(t.ClassName).Append(".__Create);\n");
            }
            foreach (var kv in named.OrderBy(kv => kv.Value, System.StringComparer.Ordinal).ThenBy(kv => kv.Key, System.StringComparer.Ordinal))
            {
                if (wrapped.Contains(kv.Key)) continue;
                sb.Append("            b.Name(typeof(").Append(kv.Key).Append("), ").Append(Names.Literal(kv.Value)).Append(");\n");
            }
            sb.Append(wrappers.ExtensionRegistration);
            sb.Append("            global::XLua.Binding.BindingApi.Register(b);\n");
            sb.Append("        }\n");
            if (assembly.HasEditorInitialize)
            {
                sb.Append("\n#if UNITY_EDITOR\n");
                sb.Append("        // Edit-mode code and tests run without entering play mode.\n");
                sb.Append("        [global::UnityEditor.InitializeOnLoadMethod]\n");
                sb.Append("        static void EditorRegister()\n        {\n            Register();\n        }\n");
                sb.Append("#endif\n");
            }
            sb.Append("    }\n}\n");
            return sb.ToString();
        }
    }
}

#!/usr/bin/env python3
"""The presets of docs/design/presets.md as data: the C# defines a preset implies,
the native options it sets and the plugin variant it selects.

C# has no project-wide #define: a symbol defined in one file is not defined in the
next. So the preset define (XLUA_PRESET_MINIMAL, a Player Settings scripting
define, a csc.rsp entry or a -define: option) is expanded at the top of every C#
file that tests one of the feature defines, by a generated block:

    // <xlua-preset> ...
    #if XLUA_PRESET_MINIMAL
    #define XLUA_NO_TEMPLATE
    ...
    #endif
    // </xlua-preset>

The code below the block keeps testing one symbol per feature. This script writes
those blocks and checks them; Test/Native/presets_check.py runs the check, and
also configures CMake with every preset and compares the cache with NATIVE.

    python3 Tools/presets.py --write      update the blocks in every C# file
    python3 Tools/presets.py --check      exit 1 if a block is missing, stale or not needed
    python3 Tools/presets.py --expect-env minimal
                                          print the XLUA_EXPECT_* variables of a preset
                                          as shell exports, for the native checks
                                          (eval "$(python3 Tools/presets.py --expect-env minimal)")
"""
import argparse
import re
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]

# C# defines each preset implies (docs/design/presets.md, the feature table).
# An entry (symbol, opt_in) defines symbol unless the positive define opt_in is
# set: XLUA_UTIL brings xlua.util back into a minimal build ("opt-in" in the table).
CSHARP = {
    "minimal": [
        ("XLUA_NO_STREAMING_ASSETS_LOADER", None),
        ("XLUA_NO_SIGNATURE_LOADER", None),
        ("XLUA_NO_TEMPLATE", None),
        ("XLUA_NO_UTIL", "XLUA_UTIL"),
        ("XLUA_NO_PROFILER", None),
        ("XLUA_NO_LOAD_ASSEMBLY", None),
        ("XLUA_LOCK_METATABLES", None),
        ("XLUA_CHECK_OBJECTS", None),
        ("XLUA_CHECK_STRUCT_ACCESSORS", None),
        ("XLUA_RESTRICT_GETMETATABLE", None),
        ("XLUA_CHECK_OBJECT_CACHE", None),
        ("XLUA_LOCK_XLUA_TABLE", None),
        ("XLUA_RESTRICT_PRIVATE_ACCESS", None),
        ("XLUA_REDUCED_DEBUG", None),
    ],
}

# Native option defaults per preset (build/xlua_presets.cmake). "platform" marks a
# value that depends on the target (see that file); presets_check.py compares the
# host configuration with these.
LUA_LIBS_ALL = ["package", "coroutine", "table", "io", "os", "string", "math", "utf8", "debug"]
LUAJIT_LIBS_ALL = ["package", "table", "io", "os", "string", "math", "debug", "bit", "jit", "ffi"]
NATIVE = {
    "legacy": {
        "XLUA_LUASOCKET": "ON", "XLUA_MIME": "ON", "XLUA_LEAK_CHECKER": "ON", "XLUA_UINT64": "ON",
        "XLUA_MEMORY_SNAPSHOT": "platform", "XLUA_LIBS": "all", "XLUA_EXPORTS": "platform-all",
        "XLUA_HARDEN": "OFF", "XLUA_ICF": "ON", "XLUA_LUASCRIPT": "OFF", "XLUA_BUFFER": "OFF",
        "XLUA_OS_FULL": "ON", "XLUA_LOADLIB": "ON", "XLUA_DOFILE": "ON",
        "XLUA_BYTECODE_ONLY": "OFF", "XLUA_TRUSTED_BYTECODE": "OFF",
    },
    "minimal": {
        "XLUA_LUASOCKET": "OFF", "XLUA_MIME": "OFF", "XLUA_LEAK_CHECKER": "OFF", "XLUA_UINT64": "ON",
        "XLUA_MEMORY_SNAPSHOT": "OFF",
        "XLUA_LIBS": [l for l in LUA_LIBS_ALL if l != "io"],
        "XLUA_LIBS_LUAJIT": [l for l in LUAJIT_LIBS_ALL if l != "io"],
        # managed for ELF shared libraries (Android, OpenHarmony, Linux), all elsewhere.
        "XLUA_EXPORTS": "platform-managed",
        "XLUA_HARDEN": "OFF", "XLUA_ICF": "ON", "XLUA_LUASCRIPT": "OFF", "XLUA_BUFFER": "OFF",
        # os with time, clock, date and difftime; no C modules, dofile or loadfile.
        "XLUA_OS_FULL": "OFF", "XLUA_LOADLIB": "OFF", "XLUA_DOFILE": "OFF",
        "XLUA_BYTECODE_ONLY": "OFF", "XLUA_TRUSTED_BYTECODE": "OFF",
    },
    # LuaScript without the bridge (docs/design/core-luascript.md): Lua 5.4 and 5.5
    # only, the safe libraries, none of the bridge's parts.
    "core": {
        "XLUA_LUASOCKET": "OFF", "XLUA_MIME": "OFF", "XLUA_LEAK_CHECKER": "OFF", "XLUA_UINT64": "OFF",
        "XLUA_MEMORY_SNAPSHOT": "OFF",
        "XLUA_LIBS": ["coroutine", "table", "string", "math", "utf8"],
        "XLUA_EXPORTS": "platform-managed",
        "XLUA_HARDEN": "OFF", "XLUA_ICF": "ON", "XLUA_LUASCRIPT": "ON",
        # LuaScript's buffer library (LuaLibs.Buffer, milestone 10).
        "XLUA_BUFFER": "ON",
        # No os or package; lbaselib.c keeps dofile and loadfile, which the sandbox never exposes.
        "XLUA_OS_FULL": "ON", "XLUA_LOADLIB": "ON", "XLUA_DOFILE": "ON",
        "XLUA_BYTECODE_ONLY": "OFF", "XLUA_TRUSTED_BYTECODE": "OFF",
    },
}

# The plugin variant (Plugins/.../xlua-variants/<name>/) a preset define selects.
VARIANT = {"minimal": "minimal"}

BEGIN = "// <xlua-preset> generated by Tools/presets.py from docs/design/presets.md; do not edit"
END = "// </xlua-preset>"


def define(preset):
    return "XLUA_PRESET_" + preset.upper()


def implied_symbols():
    return {symbol for entries in CSHARP.values() for symbol, _ in entries}


def block(newline="\n"):
    lines = [BEGIN]
    for preset, entries in CSHARP.items():
        lines.append("#if " + define(preset))
        for symbol, opt_in in entries:
            if opt_in:
                lines += ["#if !" + opt_in, "#define " + symbol, "#endif"]
            else:
                lines.append("#define " + symbol)
        lines.append("#endif")
    lines.append(END)
    return newline.join(lines) + newline


DIRECTIVE = re.compile(r"^\s*#\s*(if|elif)\b(.*)$", re.M)
CONDITIONAL = re.compile(r"Conditional\(\s*\"(\w+)\"\s*\)")
BLOCK = re.compile(re.escape(BEGIN) + r".*?" + re.escape(END) + r"\r?\n", re.S)


def uses(text):
    """The implied symbols a C# file tests in #if/#elif or [Conditional], without its block."""
    text = BLOCK.sub("", text)
    symbols = implied_symbols()
    found = set()
    for _, expression in DIRECTIVE.findall(text):
        found |= {s for s in re.findall(r"\w+", expression) if s in symbols}
    return found


def conditional_problems(path, text):
    """[Conditional("X")] is decided where the method is called, so a method that is
    conditional on an implied symbol must also be conditional on the preset define."""
    problems = []
    symbols = implied_symbols()
    for match in CONDITIONAL.finditer(text):
        if match.group(1) not in symbols:
            continue
        around = text[max(0, match.start() - 200):match.end() + 200]
        for preset, entries in CSHARP.items():
            if any(s == match.group(1) for s, _ in entries) and 'Conditional("%s")' % define(preset) not in around:
                problems.append('%s: [Conditional("%s")] needs [Conditional("%s")] next to it'
                                % (path, match.group(1), define(preset)))
    return problems


def insert_at(text):
    """Where a #define may go: after a byte order mark and the leading comments."""
    pos = 1 if text.startswith("﻿") else 0
    while True:
        rest = text[pos:]
        stripped = rest.lstrip(" \t\r\n")
        skipped = len(rest) - len(stripped)
        if stripped.startswith("//") and not stripped.startswith(BEGIN):
            end = stripped.find("\n")
            pos += skipped + (len(stripped) if end < 0 else end + 1)
        elif stripped.startswith("/*"):
            end = stripped.find("*/")
            line_end = stripped.find("\n", end)
            pos += skipped + (len(stripped) if line_end < 0 else line_end + 1)
        else:
            return pos


def cs_files():
    out = subprocess.run(["git", "-C", str(REPO), "ls-files", "*.cs"], stdout=subprocess.PIPE, text=True, check=True).stdout
    return [REPO / line for line in out.splitlines() if line and not line.startswith("docs/")]


def expected_text(text):
    """The file with its block added, updated or removed as its uses need."""
    newline = "\r\n" if "\r\n" in text else "\n"
    without = BLOCK.sub("", text)
    if not uses(text):
        return without
    pos = insert_at(without)
    return without[:pos] + block(newline) + without[pos:]


def expect_env(preset):
    """The XLUA_EXPECT_* variables (Test/Native/managed_imports.py, native_regression.py,
    run_managed.py) for a library built with a preset's defaults, on any runtime: the
    checks ignore library names of the other runtime, and LuaJIT has no leak checker."""
    native = NATIVE[preset]
    env = {"XLUA_EXPECT_UINT64": native["XLUA_UINT64"],
           "XLUA_EXPECT_MEMORY_SNAPSHOT": native["XLUA_MEMORY_SNAPSHOT"]}
    if native["XLUA_MEMORY_SNAPSHOT"] == "platform":
        del env["XLUA_EXPECT_MEMORY_SNAPSHOT"]
    if native["XLUA_LEAK_CHECKER"] == "OFF":
        env["XLUA_EXPECT_LEAK_CHECKER"] = "OFF"
    modules = []
    if native["XLUA_LUASOCKET"] == "ON":
        modules.append("socket")
        if native["XLUA_MIME"] == "ON":
            modules.append("mime")
    env["XLUA_EXPECT_NATIVE_MODULES"] = ",".join(modules)
    libs = native["XLUA_LIBS"]
    if not isinstance(libs, str):
        libs = ",".join(libs + [l for l in native.get("XLUA_LIBS_LUAJIT", []) if l not in libs])
    env["XLUA_EXPECT_LIBS"] = libs
    for option in ("XLUA_OS_FULL", "XLUA_LOADLIB", "XLUA_DOFILE"):
        env["XLUA_EXPECT_" + option[len("XLUA_"):]] = native[option]
    return env


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    g = p.add_mutually_exclusive_group(required=True)
    g.add_argument("--write", action="store_true")
    g.add_argument("--check", action="store_true")
    g.add_argument("--expect-env", metavar="PRESET", choices=sorted(NATIVE))
    a = p.parse_args()
    if a.expect_env:
        for key, value in expect_env(a.expect_env).items():
            print("export %s=%s" % (key, "'" + value + "'"))
        return 0
    problems = []
    for path in cs_files():
        raw = path.read_bytes()
        text = raw.decode("utf-8", "surrogateescape")
        rel = path.relative_to(REPO)
        problems += conditional_problems(rel, text)
        wanted = expected_text(text)
        if wanted == text:
            continue
        if a.write:
            path.write_bytes(wanted.encode("utf-8", "surrogateescape"))
            print("updated", rel)
        else:
            problems.append("%s: the <xlua-preset> block is %s (python3 Tools/presets.py --write)"
                            % (rel, "missing or stale" if uses(text) else "not needed"))
    for problem in problems:
        print(problem, file=sys.stderr)
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())

    sealed class LuaIndexes
    {
        // LuaEnv sets it from xlua_get_registry_index (it differs between Lua versions).
        static volatile int registryIndex = -10000;

        public static int LUA_REGISTRYINDEX
        {
            get
            {
                return registryIndex;
            }
            set
            {
                registryIndex = value;
            }
        }

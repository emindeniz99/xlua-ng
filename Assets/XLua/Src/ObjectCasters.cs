            if (LuaAPI.xlua_plen(L, idx, out len) != 0)
            {
                translator.luaEnv.ThrowExceptionFromError(LuaAPI.lua_gettop(L) - 1);
            }
            return len;
        }

        public ObjectCasters(ObjectTranslator translator)
        {
            this.translator = translator;
            castersMap[typeof(char)] = charCaster;
            castersMap[typeof(sbyte)] = sbyteCaster;
            castersMap[typeof(byte)] = byteCaster;
            castersMap[typeof(short)] = shortCaster;
            castersMap[typeof(ushort)] = ushortCaster;
            castersMap[typeof(int)] = intCaster;
            castersMap[typeof(uint)] = uintCaster;
            castersMap[typeof(long)] = longCaster;
            castersMap[typeof(ulong)] = ulongCaster;
            castersMap[typeof(double)] = getDouble;
            castersMap[typeof(float)] = floatCaster;
            castersMap[typeof(decimal)] = decimalCaster;
            castersMap[typeof(bool)] = getBoolean;
            castersMap[typeof(string)] =  getString;
            castersMap[typeof(object)] = getObject;
            castersMap[typeof(byte[])] = getBytes;
            castersMap[typeof(IntPtr)] = getIntptr;
            //special type
            castersMap[typeof(LuaTable)] = getLuaTable;
            castersMap[typeof(LuaFunction)] = getLuaFunction;
        }

        // Integer parameters, fields and properties that Lua sets (GetArgCaster):
        // Lua's rule through LuaDLL.cs xlua_check*, whose error names the
        // argument, as in generated and emitted wrappers. The casters below
        // (castersMap) apply the same rule through xlua_get* to values C# reads
        // from Lua (delegate results, LuaTable.Get), table contents, array
        // elements, enums and nullable integers.
        Dictionary<Type, ObjectCast> argCastersMap = new Dictionary<Type, ObjectCast>()
        {
            {typeof(char), (L, idx, target) => LuaAPI.xlua_checkchar(L, idx)},
            {typeof(sbyte), (L, idx, target) => LuaAPI.xlua_checksbyte(L, idx)},
            {typeof(byte), (L, idx, target) => LuaAPI.xlua_checkbyte(L, idx)},
            {typeof(short), (L, idx, target) => LuaAPI.xlua_checkint16(L, idx)},
            {typeof(ushort), (L, idx, target) => LuaAPI.xlua_checkuint16(L, idx)},
            {typeof(int), (L, idx, target) => LuaAPI.xlua_checkint32(L, idx)},
            {typeof(uint), (L, idx, target) => LuaAPI.xlua_checkuint32(L, idx)},
            {typeof(long), (L, idx, target) => LuaAPI.xlua_checkinteger(L, idx)},
            {typeof(ulong), (L, idx, target) => LuaAPI.xlua_checkuint64(L, idx)},
        };

        // The caster for a value Lua passes to a C# parameter or assigns to a
        // field, property or indexer: the integer types follow Lua's rule
        // (argCastersMap), a UnityEngine.Object type raises luaL_argerror's
        // text for a table (RefusesTables), everything else uses GetCaster.
        public ObjectCast GetArgCaster(Type type)
        {
            ObjectCast oc;
            if (TryGetIntegerArgCaster(type, out oc))
            {
                return oc;
            }
            if (type.IsByRef) type = type.GetElementType();
            if (!refusingArgCasters.TryGetValue(type, out oc))
            {
                // null: the type takes tables as before (GetCaster).
                oc = RefusesTables(type) ? genRefusingCaster(type, true) : IsStrictStruct(type) ? genStructArgCaster(type)
                    : type.IsEnum() ? genEnumArgCaster(type) : null;
                refusingArgCasters.Add(type, oc);
            }
            return oc ?? GetCaster(type);
        }

        // A struct that Lua must pass as a struct: a value type other than a
        // primitive, an enum, decimal or Nullable<T>. Given nil, a number, a
        // string or nothing as a parameter, field or property, every binding
        // mode raises StructExpected (owner decision of 2026-10-28,
        // docs/research/binding-mode-parity.md): generated code threw
        // NullReferenceException, emitted and reflection wrappers passed the
        // struct's zero value. A Nullable<T> still takes nil, and an omitted
        // optional parameter its default.
        public static bool IsStrictStruct(Type type)
        {
            return type.IsValueType() && !type.IsPrimitive() && !type.IsEnum() && type != typeof(decimal)
                && Nullable.GetUnderlyingType(type) == null;
        }

        // A strict struct or an enum (not Nullable<E>): an argument of such a
        // type given a value that is not one raises StructExpected in every
        // binding mode. Enums since owner decision Q34 of 2026-10-28: generated
        // code threw NullReferenceException or "invalid value for enum E" for
        // nil, the emitted and reflection wrappers the latter.
        public static bool IsStrictArg(Type type)
        {
            return IsStrictStruct(type) || type.IsEnum();
        }

        // A strict struct S or a Nullable<S>: a value of such a type that C#
        // reads back from Lua (ObjectTranslator.GetStructResult) raises
        // StructExpected for a value of another kind in every binding mode,
        // owner decisions Q56 (S) and Q59 (Nullable<S>) of 2026-10-28.
        public static bool IsStrictResult(Type type)
        {
            return IsStrictStruct(Nullable.GetUnderlyingType(type) ?? type);
        }

        // The error of a value that is no struct of the type: an
        // InvalidCastException, as for a UnityEngine.Object type given a table
        // in a value C# reads, which every wrapper reports as
        // "c# exception:System.InvalidCastException: T expected, got nil".
        internal static Exception StructExpected(RealStatePtr L, int idx, Type type)
        {
            return StructExpected(L, idx, type.ToString());
        }

        // StructExpected with the type as a name (the generated GCOptimize
        // readers pass the name they print).
        internal static Exception StructExpected(RealStatePtr L, int idx, string typeName)
        {
            string got;
            switch (LuaAPI.lua_type(L, idx))
            {
                case LuaTypes.LUA_TNONE: got = "no value"; break;
                case LuaTypes.LUA_TNIL: got = "nil"; break;
                case LuaTypes.LUA_TBOOLEAN: got = "boolean"; break;
                case LuaTypes.LUA_TNUMBER: got = "number"; break;
                case LuaTypes.LUA_TSTRING: got = "string"; break;
                case LuaTypes.LUA_TTABLE: got = "table"; break;
                case LuaTypes.LUA_TFUNCTION: got = "function"; break;
                case LuaTypes.LUA_TTHREAD: got = "thread"; break;
                default:
                    // A C# object names its class (owner decision Q36).
                    ObjectTranslator translator = ObjectTranslatorPool.Instance.Find(L);
                    object obj = translator == null ? null : translator.SafeGetCSObj(L, idx);
                    got = obj == null ? "userdata" : obj.GetType().ToString();
                    break;
            }
            return new InvalidCastException(typeName + " expected, got " + got);
        }

        // GetCaster's caster of a strict struct, which returns null for a value
        // that is not one: StructExpected instead. nil and nothing are refused
        // before the caster, since a GCOptimize type's caster (its generated
        // reader) gives default(T) for them, as a result C# reads back from Lua
        // should (owner decision Q35 of 2026-10-28).
        ObjectCast genStructArgCaster(Type type)
        {
            ObjectCast caster = GetCaster(type);
            return (RealStatePtr L, int idx, object target) =>
            {
                LuaTypes lua_type = LuaAPI.lua_type(L, idx);
                object obj = lua_type == LuaTypes.LUA_TNIL || lua_type == LuaTypes.LUA_TNONE ? null : caster(L, idx, target);
                if (obj == null)
                {
                    throw StructExpected(L, idx, type);
                }
                return obj;
            };
        }

        // GetCaster's caster of an enum for an argument (owner decision Q34): a
        // number, a value name or the enum's own userdata as before; nil,
        // nothing, a boolean, a table, a function or a C# object of another
        // class raise StructExpected (the caster threw "invalid value for enum
        // E", which results C# reads back from Lua keep).
        ObjectCast genEnumArgCaster(Type type)
        {
            ObjectCast caster = GetCaster(type);
            return (RealStatePtr L, int idx, object target) =>
            {
                switch (LuaAPI.lua_type(L, idx))
                {
                    case LuaTypes.LUA_TNUMBER:
                    case LuaTypes.LUA_TSTRING:
                        return caster(L, idx, target);
                    case LuaTypes.LUA_TUSERDATA:
                        object obj = translator.SafeGetCSObj(L, idx);
                        if (obj == null || type.IsInstanceOfType(obj))
                        {
                            return caster(L, idx, target);
                        }
                        break;
                }
                throw StructExpected(L, idx, type);
            };
        }

        // GetArgCaster's casters for the types that refuse tables, and null for
        // the others, so that each type is tested once.
        Dictionary<Type, ObjectCast> refusingArgCasters = new Dictionary<Type, ObjectCast>();

        const string unityObjectName = "UnityEngine.Object";

        // Tencent/xLua#918: a Lua table never converts to UnityEngine.Object or
        // a type derived from it (GameObject, Component, ScriptableObject...).
        // Other classes with a default constructor are made from a table field
        // by field, which for these types put a new, empty object into the
        // scene (GameObject) or one Unity cannot use (a MonoBehaviour or
        // ScriptableObject made with new). The overload check does not accept a
        // table for them, and the conversion raises "UnityEngine.GameObject
        // expected, got table" instead: with luaL_argerror's prefix for a
        // parameter, field or property that Lua sets, as an InvalidCastException
        // for a value C# reads from Lua (a delegate or interface result,
        // LuaTable.Get). The base class is found by name, so that the rule is the
        // same in the Editor, in players, in the source generator (it tests the
        // type when it writes a wrapper) and outside Unity, where the tests define a stand-in
        // UnityEngine.Object (Test/UnitTest/xLuaTest/LuaCallCS/UpstreamForLuaCallCS.cs).
        public static bool RefusesTables(Type type)
        {
            if (type == null) return false;
            if (type.IsByRef) type = type.GetElementType();
            if (!type.IsClass()) return false;
            for (Type t = type; t != null; t = t.BaseType())
            {
                if (t.FullName == unityObjectName) return true;
            }
            return false;
        }

        // The error of a table where a type that refuses tables is expected:
        // luaL_argerror's text for an argument of the running C function (a
        // LuaException, as C# cannot raise the Lua error itself), and an
        // InvalidCastException without the argument for a value C# reads.
        static Exception tableRefused(RealStatePtr L, int idx, Type type, bool argument)
        {
            string msg = type + " expected, got table";
            if (!argument)
            {
                return new InvalidCastException(msg);
            }
            LuaAPI.xlua_pushargerror(L, idx, msg);
            string message = LuaAPI.lua_tostring(L, -1);
            LuaAPI.lua_pop(L, 1);
            return new LuaException(message);
        }

        // The caster of a type that refuses tables: the C# object if it has the
        // type, an error for a table, null for anything else (as before).
        ObjectCast genRefusingCaster(Type type, bool argument)
        {
            return (RealStatePtr L, int idx, object target) =>
            {
                LuaTypes lua_type = LuaAPI.lua_type(L, idx);
                if (lua_type == LuaTypes.LUA_TUSERDATA)
                {
                    object obj = translator.SafeGetCSObj(L, idx);
                    return (obj != null && type.IsAssignableFrom(obj.GetType())) ? obj : null;
                }
                if (lua_type == LuaTypes.LUA_TTABLE)
                {
                    throw tableRefused(L, idx, type, argument);
                }
                return null;
            };
        }


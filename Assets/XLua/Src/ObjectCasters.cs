        // The cost of the value at idx for a parameter of this kind (see above).
        internal static int Arg(ObjectTranslator translator, RealStatePtr L, int idx, int kind, Type type)
        {
            int nullable = (kind & KindNullable) != 0 ? 1 : 0;
            kind &= KindNullable - 1;
            if (kind >= KindInt32 && kind <= KindDecimal)
            {
                // One call for the common case: a number for a numeric parameter.
                int number = LuaAPI.xlua_number_kind(L, idx);
                if (number != 0) return Number(number, kind) + nullable;
            }
            else if (kind == KindObject)
            {
                return ObjectCost(LuaAPI.lua_type(L, idx));
            }
            switch (LuaAPI.lua_type(L, idx))
            {
                case LuaTypes.LUA_TNUMBER:
                    return Number(LuaAPI.xlua_number_kind(L, idx), kind) + nullable;
                case LuaTypes.LUA_TSTRING:
                    return kind == KindString ? 0 : kind == KindBytes ? 2 : Mismatch;
                case LuaTypes.LUA_TBOOLEAN:
                    return kind == KindBoolean ? nullable : Mismatch;
                case LuaTypes.LUA_TLIGHTUSERDATA:
                    return kind == KindOther ? 0 : Mismatch;
                case LuaTypes.LUA_TUSERDATA:
                    switch (kind)
                    {
                        case KindOther:
                            return type == null ? nullable : Distance(translator, translator.UserdataType(L, idx), type) + nullable;
                        case KindInt64:
                        case KindUInt64:
                        case KindDecimal:
                        case KindBytes:
                            return nullable;
                        default:
                            return Mismatch;
                    }
                default:
                    return 0;
            }
        }


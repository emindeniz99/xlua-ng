    // Writes LuaCATS (lua-language-server) definition files for the C# API that
    // Lua sees through xLua: the LuaCallCSharp and ReflectionUse types, their
    // base classes, and the xlua helper globals. The files are only read by
    // editors; they never run.
    public static partial class Generator
    {
        const string LuaCATSMarker = "-- Generated by xLua LuaCATS generator. Do not edit.";

        static readonly HashSet<string> luaKeywords = new HashSet<string>()
        {
            "and", "break", "do", "else", "elseif", "end", "false", "for", "function", "goto", "if", "in",
            "local", "nil", "not", "or", "repeat", "return", "then", "true", "until", "while"
        };

        static readonly Dictionary<string, string> luaCATSOperators = new Dictionary<string, string>()
        {
            { "op_Addition", "add" }, { "op_Subtraction", "sub" }, { "op_Multiply", "mul" },
            { "op_Division", "div" }, { "op_Modulus", "mod" }, { "op_UnaryNegation", "unm" },
            { "op_BitwiseAnd", "band" }, { "op_BitwiseOr", "bor" }, { "op_ExclusiveOr", "bxor" },
            { "op_OnesComplement", "bnot" }, { "op_LeftShift", "shl" }, { "op_RightShift", "shr" },
        };

        class LuaCATSWriter
        {
            // true when the Lua runtime has a native integer subtype (Lua 5.3+).
            public bool HasIntegers;
            // Types declared with their members.
            public HashSet<Type> Full = new HashSet<Type>();
            // Every class or delegate type named somewhere in the output.
            public HashSet<Type> Referenced = new HashSet<Type>();
            public List<Type> ExtensionHolders = new List<Type>();

            string IntegerName { get { return HasIntegers ? "integer" : "number"; } }

            static bool isNamed(Type type, string fullName)
            {
                return type.FullName == fullName;
            }

            static bool isDelegateType(Type type)
            {
                return typeof(Delegate).IsAssignableFrom(type) && type != typeof(Delegate) && type != typeof(MulticastDelegate);
            }

            // Lua path of a type below CS, for example "UnityEngine.GameObject".
            // Nested types use '.', as xLua resolves CS.Outer.Inner. Constructed
            // generic types get their arguments appended with '_' because
            // LuaCATS names cannot contain '<' or ','.
            public static string LuaPath(Type type)
            {
                string name = type.Name;
                int tick = name.IndexOf('`');
                if (tick >= 0) name = name.Substring(0, tick);
                Type declaring = type.DeclaringType;
                if (type.IsGenericType && !type.IsGenericTypeDefinition)
                {
                    var args = type.GetGenericArguments();
                    // Reflection reports List<int>.Enumerator as nested in List<T>:
                    // its leading arguments belong to the declaring type.
                    if (type.IsNested && declaring.IsGenericTypeDefinition)
                    {
                        int outer = declaring.GetGenericArguments().Length;
                        declaring = declaring.MakeGenericType(args.Take(outer).ToArray());
                        args = args.Skip(outer).ToArray();
                    }
                    if (args.Length > 0)
                    {
                        name = name + "_" + string.Join("_", args.Select(a => argName(a)).ToArray());
                    }
                }
                string prefix = type.IsNested ? LuaPath(declaring) : type.Namespace;
                return string.IsNullOrEmpty(prefix) ? name : prefix + "." + name;
            }

            static string argName(Type type)
            {
                if (type.IsArray) return argName(type.GetElementType()) + "Array";
                if (type.IsGenericParameter) return type.Name;
                return LuaPath(type).Replace('.', '_');
            }

            public static string ClassName(Type type)
            {
                return "CS." + LuaPath(type);
            }

            // Constructed generic types and types nested in them are not reachable
            // by a plain CS.a.b.c path, so they are declared on a local table.
            public bool HasGlobalPath(Type type)
            {
                if (type.IsGenericType) return false;
                if (!type.IsNested) return true;
                return Full.Contains(type.DeclaringType) && HasGlobalPath(type.DeclaringType);
            }

            static bool acceptsTable(Type type)
            {
                if (type.IsPrimitive || type.IsEnum || type == typeof(string) || type == typeof(decimal)) return false;
                if (type.IsInterface || type.IsArray) return true;
                if (type.IsValueType) return true;
                return type.IsClass && !type.IsAbstract && type.GetConstructor(Type.EmptyTypes) != null;
            }

            // Lua type of a C# type. forInput: the value comes from Lua (a
            // parameter), where xLua also converts tables to structs, classes
            // with a default constructor, interfaces and arrays.
            public string TypeName(Type type, bool forInput)
            {
                if (type.IsByRef) type = type.GetElementType();
                if (type == typeof(void)) return "nil";
                if (type.IsGenericParameter)
                {
                    var constraint = type.GetGenericParameterConstraints().FirstOrDefault(c => c.IsClass && c != typeof(ValueType));
                    return constraint == null ? "any" : TypeName(constraint, forInput);
                }
                if (type.ContainsGenericParameters && !type.IsArray) return "any";
                Type underlying = Nullable.GetUnderlyingType(type);
                if (underlying != null)
                {
                    string inner = TypeName(underlying, forInput);
                    return inner.Contains("|") ? inner + "|nil" : inner + "?";
                }
                if (type == typeof(bool)) return "boolean";
                if (type == typeof(string)) return "string";
                if (type == typeof(byte[])) return "string";
                if (type == typeof(float) || type == typeof(double)) return "number";
                if (type == typeof(sbyte) || type == typeof(byte) || type == typeof(short) || type == typeof(ushort)
                    || type == typeof(int) || type == typeof(uint) || type == typeof(long) || type == typeof(ulong)
                    || type == typeof(char))
                {
                    return IntegerName;
                }
                if (type == typeof(IntPtr) || type == typeof(UIntPtr)) return "lightuserdata";
                if (type == typeof(object) || type == typeof(ValueType)) return "any";
                if (isNamed(type, "XLua.LuaTable")) return "table";
                if (isNamed(type, "XLua.LuaFunction") || type == typeof(Delegate) || type == typeof(MulticastDelegate)) return "function";
                if (type.IsPointer || isNamed(type, "XLua.LuaBase")) return "any";
                if (type.IsArray)
                {
                    if (type.GetArrayRank() != 1) return TypeName(typeof(Array), false);
                    string element = TypeName(type.GetElementType(), false);
                    if (element.Contains("|") || element.EndsWith("?")) element = "(" + element + ")";
                    return forInput ? element + "[]|xlua.Array<" + element + ">" : "xlua.Array<" + element + ">";
                }
                Referenced.Add(type);
                string name = ClassName(type);
                return forInput && acceptsTable(type) ? name + "|table" : name;
            }

            static string luaName(string name, int index)
            {
                if (string.IsNullOrEmpty(name)) return "arg" + index;
                return luaKeywords.Contains(name) ? name + "_" : name;
            }

            static bool isLuaIdentifier(string name)
            {
                if (string.IsNullOrEmpty(name) || luaKeywords.Contains(name)) return false;
                if (!(char.IsLetter(name[0]) || name[0] == '_') || name[0] > 127) return false;
                return name.All(c => c < 128 && (char.IsLetterOrDigit(c) || c == '_'));
            }

            public class Param
            {
                public string Name;
                public string Type;
                public bool Optional;
                public bool Vararg;
            }

            public class Signature
            {
                public List<Param> Params = new List<Param>();
                public List<KeyValuePair<string, string>> Returns = new List<KeyValuePair<string, string>>();

                // Signature without parameter names: overloads that only differ in
                // C# types Lua cannot tell apart (int and short) collapse into one.
                public string TypeKey()
                {
                    return string.Join(", ", Params.Select(p => (p.Vararg ? "..." : p.Optional ? "?" : "") + p.Type).ToArray())
                        + " -> " + string.Join(", ", Returns.Select(r => r.Key).ToArray());
                }

                public string FunType(string self)
                {
                    var ps = new List<string>();
                    if (self != null) ps.Add("self: " + self);
                    foreach (var p in Params)
                    {
                        ps.Add(p.Vararg ? "...: " + p.Type : p.Name + (p.Optional ? "?" : "") + ": " + p.Type);
                    }
                    string ret = Returns.Count == 0 ? "" : ": " + string.Join(", ", Returns.Select(r => r.Key).ToArray());
                    return "fun(" + string.Join(", ", ps.ToArray()) + ")" + ret;
                }
            }

            // Lua view of a C# method: out parameters leave the argument list,
            // and the return value is followed by every out and ref parameter.
            public Signature MakeSignature(MethodBase method, bool skipFirst, Type constructed)
            {
                var sig = new Signature();
                var parameters = method.GetParameters();
                for (int i = skipFirst ? 1 : 0; i < parameters.Length; i++)
                {
                    var p = parameters[i];
                    var pt = p.ParameterType;
                    bool outOnly = p.IsOut && pt.IsByRef;
                    if (!outOnly)
                    {
                        bool vararg = i == parameters.Length - 1 && pt.IsArray && p.IsDefined(typeof(ParamArrayAttribute), false);
                        sig.Params.Add(new Param()
                        {
                            Name = luaName(p.Name, i),
                            Type = vararg ? TypeName(pt.GetElementType(), true) : TypeName(pt, true),
                            Optional = p.IsOptional,
                            Vararg = vararg,
                        });
                    }
                }
                if (constructed != null)
                {
                    Referenced.Add(constructed);
                    sig.Returns.Add(new KeyValuePair<string, string>(ClassName(constructed), null));
                }
                else
                {
                    var mi = method as MethodInfo;
                    if (mi != null && mi.ReturnType != typeof(void))
                    {
                        sig.Returns.Add(new KeyValuePair<string, string>(TypeName(mi.ReturnType, false), null));
                    }
                }
                for (int i = skipFirst ? 1 : 0; i < parameters.Length; i++)
                {
                    var p = parameters[i];
                    if (p.IsOut || p.ParameterType.IsByRef)
                    {
                        sig.Returns.Add(new KeyValuePair<string, string>(TypeName(p.ParameterType, false), luaName(p.Name, i)));
                    }
                }
                return sig;
            }

            public string DelegateAlias(Type type)
            {
                var invoke = type.GetMethod("Invoke");
                if (invoke == null) return "function";
                var sig = new Signature();
                var parameters = invoke.GetParameters();
                for (int i = 0; i < parameters.Length; i++)
                {
                    var p = parameters[i];
                    if (!(p.IsOut && p.ParameterType.IsByRef))
                    {
                        sig.Params.Add(new Param() { Name = luaName(p.Name, i), Type = TypeName(p.ParameterType, false) });
                    }
                }
                if (invoke.ReturnType != typeof(void))
                {
                    sig.Returns.Add(new KeyValuePair<string, string>(TypeName(invoke.ReturnType, false), null));
                }
                foreach (var p in parameters.Where(p => p.IsOut || p.ParameterType.IsByRef))
                {
                    sig.Returns.Add(new KeyValuePair<string, string>(TypeName(p.ParameterType, false), null));
                }
                return sig.FunType(null);
            }

            static void appendFunction(StringBuilder sb, Signature sig, IEnumerable<string> overloads, string head)
            {
                foreach (var p in sig.Params)
                {
                    sb.Append("---@param ").Append(p.Vararg ? "..." : p.Name + (p.Optional ? "?" : "")).Append(' ').Append(p.Type).Append('\n');
                }
                foreach (var r in sig.Returns)
                {
                    sb.Append("---@return ").Append(r.Key);
                    if (r.Value != null) sb.Append(' ').Append(r.Value);
                    sb.Append('\n');
                }
                foreach (var o in overloads)
                {
                    sb.Append("---@overload ").Append(o).Append('\n');
                }
                sb.Append(head).Append('(')
                    .Append(string.Join(", ", sig.Params.Select(p => p.Vararg ? "..." : p.Name).ToArray()))
                    .Append(") end\n\n");
            }

            static List<Type> interfaceParents(Type type, HashSet<Type> known)
            {
                return type.GetInterfaces().Where(i => known.Contains(i) && IsPublic(i))
                    .OrderBy(i => ClassName(i), StringComparer.Ordinal).ToList();
            }

            // Nearest base class Lua can name; non-public bases are skipped.
            public static Type LuaBase(Type type)
            {
                if (type.IsInterface) return null;
                var b = type.BaseType;
                while (b != null && !isLuaCATSCandidate(b)) b = b.BaseType;
                return b;
            }

            static string classHeader(Type type, HashSet<Type> known)
            {
                var parents = new List<string>();
                if (LuaBase(type) != null) parents.Add(ClassName(LuaBase(type)));
                parents.AddRange(interfaceParents(type, known).Select(i => ClassName(i)));
                return "---@class " + ClassName(type) + (parents.Count > 0 ? " : " + string.Join(", ", parents.ToArray()) : "") + "\n";
            }

            IEnumerable<MethodInfo> extensionMethods(Type type)
            {
                if (type.IsInterface) return new MethodInfo[0];
                return from holder in ExtensionHolders
                       from method in holder.GetMethods(BindingFlags.Static | BindingFlags.Public)
                       where isSupportedExtensionMethod(method, type) && !isMethodInBlackList(method) && !isObsolete(method)
                       select method;
            }

            static string accessPrefix(Type type, bool global)
            {
                return global ? ClassName(type) : "M";
            }

            // Members of one class, mirroring what getClassInfo hands to the
            // wrapper template. DoNotGen members stay: xLua reaches them lazily.
            public string ClassBody(Type type, out string headerTail)
            {
                const BindingFlags flags = BindingFlags.Public | BindingFlags.Instance | BindingFlags.Static | BindingFlags.DeclaredOnly;
                var sb = new StringBuilder();
                var tail = new StringBuilder();
                bool global = HasGlobalPath(type);
                string self = ClassName(type);
                string prefix = accessPrefix(type, global);

                if (type.IsEnum)
                {
                    var values = type.GetFields(BindingFlags.Public | BindingFlags.Static)
                        .Where(f => !isObsolete(f) && !isMemberInBlackList(f))
                        .Select(f => new { f.Name, Value = Convert.ToDecimal(f.GetRawConstantValue()) })
                        .OrderBy(f => f.Value).ThenBy(f => f.Name, StringComparer.Ordinal);
                    foreach (var v in values)
                    {
                        tail.Append("---@field ").Append(v.Name).Append(' ').Append(self).Append(" = ").Append(v.Value).Append('\n');
                    }
                    tail.Append("---@field __CastFrom fun(value: ").Append(IntegerName).Append("|string): ").Append(self).Append(" Converts a number or a member name to this enum.\n");
                    headerTail = tail.ToString();
                    return "";
                }

                var fieldLines = new SortedDictionary<string, string>(StringComparer.Ordinal);
                foreach (var prop in type.GetProperties(flags).Where(p => p.GetIndexParameters().Length == 0 && !isObsolete(p) && !isMemberInBlackList(p)))
                {
                    var getter = prop.GetGetMethod();
                    var setter = prop.GetSetMethod();
                    bool canGet = getter != null && !isObsolete(getter) && !isMemberInBlackList(getter);
                    bool canSet = setter != null && !isObsolete(setter) && !isMemberInBlackList(setter);
                    if (!canGet && !canSet) continue;
                    bool isStatic = (canGet ? getter : setter).IsStatic;
                    var notes = new List<string>();
                    if (isStatic) notes.Add("static");
                    if (!canSet) notes.Add("read-only");
                    if (!canGet) notes.Add("write-only");
                    fieldLines[prop.Name] = fieldLine(prop.Name, TypeName(prop.PropertyType, false), notes);
                }
                foreach (var field in type.GetFields(flags).Where(f => !isObsolete(f) && !isMemberInBlackList(f)))
                {
                    var notes = new List<string>();
                    if (field.IsStatic) notes.Add("static");
                    if (field.IsInitOnly || field.IsLiteral) notes.Add("read-only");
                    fieldLines[field.Name] = fieldLine(field.Name, TypeName(field.FieldType, false), notes);
                }
                foreach (var line in fieldLines.Values) tail.Append(line);

                var indexers = type.GetProperties(BindingFlags.Public | BindingFlags.Instance | BindingFlags.DeclaredOnly)
                    .Where(p => p.GetIndexParameters().Length == 1 && !isObsolete(p) && !isMemberInBlackList(p))
                    .Where(p => !p.GetIndexParameters()[0].ParameterType.IsAssignableFrom(typeof(string)))
                    .Where(p => p.GetGetMethod() != null || p.GetSetMethod() != null)
                    .Select(p => "---@field [" + TypeName(p.GetIndexParameters()[0].ParameterType, false) + "] " + TypeName(p.PropertyType, false) + "\n")
                    .Distinct().OrderBy(s => s, StringComparer.Ordinal);
                foreach (var line in indexers) tail.Append(line);

                var operators = type.GetMethods(flags)
                    .Where(m => luaCATSOperators.ContainsKey(m.Name) && !isMethodInBlackList(m) && !isObsolete(m))
                    .Select(m =>
                    {
                        var ps = m.GetParameters();
                        string op = luaCATSOperators[m.Name];
                        if (ps.Length == 1 && ps[0].ParameterType == type)
                            return "---@operator " + op + ": " + TypeName(m.ReturnType, false) + "\n";
                        if (ps.Length == 2 && ps[0].ParameterType == type)
                            return "---@operator " + op + "(" + TypeName(ps[1].ParameterType, false) + "): " + TypeName(m.ReturnType, false) + "\n";
                        return null;
                    })
                    .Where(s => s != null).Distinct().OrderBy(s => s, StringComparer.Ordinal);
                foreach (var line in operators) tail.Append(line);

                if (!type.IsAbstract && !type.IsInterface)
                {
                    var ctors = type.GetConstructors(BindingFlags.Instance | BindingFlags.Public)
                        .Where(c => !isMethodInBlackList(c) && !isObsolete(c))
                        .OrderBy(c => OverloadCosting(c))
                        .Select(c => MakeSignature(c, false, type)).ToList();
                    // xLua constructs any struct without arguments.
                    if (type.IsValueType)
                    {
                        var empty = new Signature();
                        empty.Returns.Add(new KeyValuePair<string, string>(self, null));
                        ctors.Insert(0, empty);
                    }
                    foreach (var ctor in ctors.GroupBy(c => c.TypeKey()).Select(g => g.First()))
                    {
                        tail.Append("---@overload ").Append(ctor.FunType(null)).Append('\n');
                    }
                }
                headerTail = tail.ToString();

                var extensions = extensionMethods(type).ToArray();
                var groups = type.GetMethods(flags)
                    .Where(method => !isDefined(method, typeof(ExtensionAttribute)) || method.GetParameters()[0].ParameterType.IsInterface || method.DeclaringType != type)
                    .Where(method => !method.IsSpecialName
                        || (((method.Name == "get_Item" && method.GetParameters().Length == 1) || (method.Name == "set_Item" && method.GetParameters().Length == 2))
                            && method.GetParameters()[0].ParameterType.IsAssignableFrom(typeof(string))))
                    .Concat(extensions)
                    .Where(method => !isMethodInBlackList(method) && (!method.IsGenericMethod || extensions.Contains(method) || isSupportedGenericMethod(method)) && !isObsolete(method))
                    .GroupBy(method => new { method.Name, IsStatic = method.IsStatic && !extensions.Contains(method) })
                    .OrderBy(g => g.Key.Name, StringComparer.Ordinal).ThenBy(g => g.Key.IsStatic);

                foreach (var group in groups)
                {
                    string name = group.Key.Name;
                    bool isStatic = group.Key.IsStatic;
                    if (!isLuaIdentifier(name))
                    {
                        sb.Append("-- ").Append(name).Append(" is not a Lua identifier; use obj['").Append(name).Append("'](...).\n\n");
                        continue;
                    }
                    var sigs = group.OrderBy(m => OverloadCosting(m))
                        .Select(m => MakeSignature(m, extensions.Contains(m), null))
                        .GroupBy(s => s.TypeKey()).Select(g => g.First()).ToList();
                    var first = sigs[0];
                    var overloads = sigs.Skip(1).Select(s => s.FunType(isStatic ? null : self));
                    appendFunction(sb, first, overloads, "function " + prefix + (isStatic ? "." : ":") + name);
                }

                var events = type.GetEvents(flags)
                    .Where(e => !isObsolete(e) && !isMemberInBlackList(e) && (e.GetAddMethod() != null || e.GetRemoveMethod() != null))
                    .OrderBy(e => e.Name, StringComparer.Ordinal);
                foreach (var ev in events)
                {
                    bool isStatic = (ev.GetAddMethod() ?? ev.GetRemoveMethod()).IsStatic;
                    sb.Append("---Adds (\"+\") or removes (\"-\") a handler of the C# event ").Append(ev.Name).Append(".\n");
                    sb.Append("---@param op \"+\"|\"-\"\n");
                    sb.Append("---@param handler ").Append(TypeName(ev.EventHandlerType, true)).Append('\n');
                    sb.Append("function ").Append(prefix).Append(isStatic ? "." : ":").Append(ev.Name).Append("(op, handler) end\n\n");
                }
                return sb.ToString();
            }

            static string fieldLine(string name, string type, List<string> notes)
            {
                return "---@field " + name + " " + type + (notes.Count > 0 ? " " + string.Join(", ", notes.ToArray()) : "") + "\n";
            }

            public string ClassFile(Type type, string body, string headerTail, HashSet<Type> known)
            {
                var sb = new StringBuilder();
                sb.Append("---@meta\n").Append(LuaCATSMarker).Append("\n\n");
                sb.Append("-- C# ").Append(type.IsEnum ? "enum " : type.IsInterface ? "interface " : type.IsValueType ? "struct " : "class ")
                    .Append(type.ToString()).Append(Full.Contains(type) && !ExposedRoots.Contains(type) ? " (base class, accessed by reflection)" : "").Append('\n');
                sb.Append(classHeader(type, known));
                sb.Append(headerTail);
                bool global = HasGlobalPath(type);
                sb.Append(global ? ClassName(type) + " = {}\n\n" : "local M = {}\n\n");
                sb.Append(body);
                return sb.ToString().TrimEnd('\n') + "\n";
            }

            public HashSet<Type> ExposedRoots = new HashSet<Type>();
        }

        static bool luaHasIntegers()
        {
            object[] ret = luaenv.DoString("return math.type ~= nil");
            return ret != null && ret.Length > 0 && ret[0] is bool && (bool)ret[0];
        }

        static bool isLuaCATSCandidate(Type type)
        {
            return type != null && IsPublic(type) && !isObsolete(type) && !type.IsGenericTypeDefinition && !type.ContainsGenericParameters
                && !type.IsArray && !type.IsByRef && !type.IsPointer && !type.Name.Contains("<")
                && !typeof(Delegate).IsAssignableFrom(type);
        }

        // Writes the LuaCATS files for the current GetGenConfig result into save_path.
        static void writeLuaCATS(string save_path)
        {
            var w = new LuaCATSWriter();
            w.HasIntegers = luaHasIntegers();
            var roots = LuaCallCSharp.Concat(ReflectionUse).Where(isLuaCATSCandidate).Distinct().ToList();
            w.ExposedRoots = new HashSet<Type>(roots);
            w.ExtensionHolders = LuaCallCSharp.Concat(ReflectionUse).Distinct()
                .Where(t => t.IsSealed && t.IsAbstract && !t.IsGenericType && !t.IsNested && isDefined(t, typeof(ExtensionAttribute)))
                .OrderBy(t => t.FullName, StringComparer.Ordinal).ToList();

            // Base classes are reachable through every derived object, so they are
            // declared in full even when only the derived class is configured.
            foreach (var root in roots)
            {
                for (var t = root; t != null; t = LuaCATSWriter.LuaBase(t))
                {
                    w.Full.Add(t);
                }
            }

            var bodies = new Dictionary<Type, string>();
            var tails = new Dictionary<Type, string>();
            foreach (var type in w.Full.OrderBy(t => LuaCATSWriter.ClassName(t), StringComparer.Ordinal))
            {
                string tail;
                bodies[type] = w.ClassBody(type, out tail);
                tails[type] = tail;
            }
            // Types used in signatures (and the System.Type the helpers take) are
            // declared as empty classes so their names resolve and subtyping holds.
            w.TypeName(typeof(Type), false);
            w.TypeName(typeof(MethodBase), false);

            var stubs = new HashSet<Type>();
            var delegates = new HashSet<Type>();
            var pending = new Queue<Type>(w.Referenced);
            var seen = new HashSet<Type>(w.Referenced);
            while (pending.Count > 0)
            {
                var t = pending.Dequeue();
                if (t.IsGenericParameter || t.ContainsGenericParameters) continue;
                if (typeof(Delegate).IsAssignableFrom(t))
                {
                    delegates.Add(t);
                    w.DelegateAlias(t);
                    foreach (var r in w.Referenced.Where(x => !seen.Contains(x)).ToList())
                    {
                        seen.Add(r);
                        pending.Enqueue(r);
                    }
                    continue;
                }
                if (w.Full.Contains(t)) continue;
                stubs.Add(t);
                var baseType = LuaCATSWriter.LuaBase(t);
                if (baseType != null && !seen.Contains(baseType))
                {
                    seen.Add(baseType);
                    w.Referenced.Add(baseType);
                    pending.Enqueue(baseType);
                }
            }
            var known = new HashSet<Type>(w.Full.Concat(stubs));

            Directory.CreateDirectory(save_path);
            var written = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
            var utf8 = new UTF8Encoding(false);
            Action<string, string> save = (name, content) =>
            {
                written.Add(name);
                File.WriteAllText(Path.Combine(save_path, name), content, utf8);
            };

            foreach (var type in w.Full)
            {
                save(LuaCATSWriter.LuaPath(type) + ".lua", w.ClassFile(type, bodies[type], tails[type], known));
            }

            var cs = new StringBuilder();
            cs.Append("---@meta\n").Append(LuaCATSMarker).Append("\n\n");
            cs.Append("-- Number mapping: C# integral types are ").Append(w.HasIntegers ? "integer (Lua 5.3+)" : "number (no integer subtype)").Append(".\n\n");
            cs.Append("---Root of every C# namespace and type. Types that are not configured for\n");
            cs.Append("---generation are still reachable at run time through reflection, so unknown\n");
            cs.Append("---names are typed `any` rather than reported.\n");
            cs.Append("---@class CS\n---@field [string] any\nCS = {}\n\n");
            var namespaces = new SortedSet<string>(StringComparer.Ordinal);
            foreach (var type in w.Full.Where(t => w.HasGlobalPath(t) && !t.IsNested && !string.IsNullOrEmpty(t.Namespace)))
            {
                var parts = type.Namespace.Split('.');
                for (int i = 1; i <= parts.Length; i++)
                {
                    namespaces.Add(string.Join(".", parts.Take(i).ToArray()));
                }
            }
            foreach (var ns in namespaces)
            {
                cs.Append("---@class CS.").Append(ns).Append("\n---@field [string] any\nCS.").Append(ns).Append(" = {}\n\n");
            }
            if (stubs.Count > 0)
            {
                cs.Append("-- Types that appear in signatures but are not configured for Lua.\n\n");
                foreach (var stub in stubs.OrderBy(t => LuaCATSWriter.ClassName(t), StringComparer.Ordinal))
                {
                    var parents = new List<string>();
                    if (LuaCATSWriter.LuaBase(stub) != null) parents.Add(LuaCATSWriter.ClassName(LuaCATSWriter.LuaBase(stub)));
                    parents.AddRange(stub.GetInterfaces().Where(i => known.Contains(i)).Select(i => LuaCATSWriter.ClassName(i))
                        .OrderBy(n => n, StringComparer.Ordinal));
                    cs.Append("---@class ").Append(LuaCATSWriter.ClassName(stub))
                        .Append(parents.Count > 0 ? " : " + string.Join(", ", parents.ToArray()) : "").Append("\n\n");
                }
            }
            if (delegates.Count > 0)
            {
                cs.Append("-- Delegates: Lua functions convert to them, and C# delegates are callable.\n\n");
                foreach (var d in delegates.OrderBy(t => LuaCATSWriter.ClassName(t), StringComparer.Ordinal))
                {
                    cs.Append("---@alias ").Append(LuaCATSWriter.ClassName(d)).Append(' ').Append(w.DelegateAlias(d)).Append("\n\n");
                }
            }
            save("CS.lua", cs.ToString().TrimEnd('\n') + "\n");
            save("xlua.lua", luaCATSHelpers(w.HasIntegers));
            Directory.CreateDirectory(Path.Combine(save_path, "xlua"));
            File.WriteAllText(Path.Combine(Path.Combine(save_path, "xlua"), "util.lua"), LuaCATSUtil, utf8);

            // Remove files this generator wrote earlier for types that are gone.
            foreach (var file in Directory.GetFiles(save_path, "*.lua"))
            {
                if (written.Contains(Path.GetFileName(file))) continue;
                var lines = File.ReadAllLines(file);
                if (lines.Length > 1 && lines[1] == LuaCATSMarker) File.Delete(file);
            }
        }


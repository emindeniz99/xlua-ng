        // Entry point for XLuaGenerate --luacats.
        public static void GenLuaCATS(IEnumerable<Type> all_types, string save_path)
        {
            var start = DateTime.Now;
            refReadOnlyReported.Clear();
            var manifests = luaCATSConfig(all_types.Where(type => !type.IsGenericTypeDefinition).ToList());
            writeLuaCATS(save_path, manifests);
            Console.WriteLine("LuaCATS definitions written to " + Path.GetFullPath(save_path) + " in " + (DateTime.Now - start).TotalMilliseconds + " ms");
            luaenv.Dispose();
        }
#else
        [MenuItem("XLua/Generate LuaCATS Definitions", false, 3)]
        public static void GenLuaCATS()
        {
            var start = DateTime.Now;
            refReadOnlyReported.Clear();
            var manifests = luaCATSConfig(XLua.Utils.GetAllTypes());
            writeLuaCATS(GeneratorConfig.luacats_path, manifests);
            Debug.Log("LuaCATS definitions written to " + Path.GetFullPath(GeneratorConfig.luacats_path) + " in " + (DateTime.Now - start).TotalMilliseconds + " ms");
        }

        // Deletes only the files the generator wrote, then generates again.
        [MenuItem("XLua/Clear and Generate LuaCATS Definitions", false, 4)]
        public static void ClearAndGenLuaCATS()
        {
            int removed = ClearLuaCATS(GeneratorConfig.luacats_path);
            Debug.Log("Removed " + removed + " generated LuaCATS files from " + Path.GetFullPath(GeneratorConfig.luacats_path));
            GenLuaCATS();
        }
#endif

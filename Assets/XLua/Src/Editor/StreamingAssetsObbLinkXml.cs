// Keeps UnityEngine.WWW in Android APK builds with "Split Application Binary"
// when the StreamingAssets searcher is compiled in (owner decision Q83 of
// 2026-10-29, docs/design/presets.md, "The StreamingAssets searcher").
//
// Such a build puts StreamingAssets into the OBB file, which Android's
// AssetManager does not see. The player then reads them with WWW, as xLua did
// on every Android player before, through reflection (StreamingAssetsLoader.cs),
// so that every other player leaves out WWW and with it the UnityWebRequest and
// TLS engine modules (573,164 bytes of APK). An AAB with Split Application
// Binary puts StreamingAssets into an install-time asset pack instead, which
// the AssetManager sees, so it needs no WWW.
// <xlua-preset> generated by Tools/presets.py from docs/design/presets.md; do not edit

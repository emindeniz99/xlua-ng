using System.IO;
using UnityEditor;
using UnityEditor.Build;
using UnityEditor.Build.Reporting;
using UnityEditor.UnityLinker;

namespace XLua
{
    public static class StreamingAssetsObb
    {
        // The link.xml that keeps WWW, its engine module ignored when the project
        // removed the Unity Web Request WWW built-in package.
        public const string LinkXml =
            "<linker>\n"
            + "  <assembly fullname=\"UnityEngine.UnityWebRequestWWWModule\" ignoreIfMissing=\"1\">\n"
            + "    <type fullname=\"UnityEngine.WWW\" preserve=\"all\"/>\n"
            + "  </assembly>\n"
            + "</linker>\n";

        // Whether a build keeps WWW: an Android APK with Split Application
        // Binary, in a project that has the StreamingAssets searcher.
        public static bool KeepsWww(BuildTarget target, bool splitApplicationBinary, bool appBundle)
        {
#if XLUA_NO_STREAMING_ASSETS_LOADER
            return false;
#else
            return target == BuildTarget.Android && splitApplicationBinary && !appBundle;
#endif
        }

        public static bool SplitApplicationBinary
        {
            get
            {
#if UNITY_6000_0_OR_NEWER
                return PlayerSettings.Android.splitApplicationBinary;
#else
                return PlayerSettings.Android.useAPKExpansionFiles;
#endif
            }
        }
    }

    class StreamingAssetsObbLinkXml : IUnityLinkerProcessor
    {
        public int callbackOrder { get { return 0; } }

        public string GenerateAdditionalLinkXmlFile(BuildReport report, UnityLinkerBuildPipelineData data)
        {
            if (!StreamingAssetsObb.KeepsWww(data.target, StreamingAssetsObb.SplitApplicationBinary, EditorUserBuildSettings.buildAppBundle))
            {
                return null;
            }
            string path = Path.GetFullPath(Path.Combine("Temp", "XLuaStreamingAssets", "link.xml"));
            Directory.CreateDirectory(Path.GetDirectoryName(path));
            File.WriteAllText(path, StreamingAssetsObb.LinkXml, new System.Text.UTF8Encoding(false));
            return path;
        }
    }
}
#endif

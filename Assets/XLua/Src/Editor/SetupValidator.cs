        // Checks the hotfix injector that Tools/build_tools.py wrote to toolsPath,
        // using the manifest it writes next to it: every listed file must exist,
        // and the injector should be built from hotfixSource (null: not compared).
        // unusable is true when injection cannot work (the injector or a file it
        // needs is missing); the other problems only mean the tools are older
        // than the project's xLua.
        public static List<string> CheckHotfixTools(string toolsPath, string hotfixSource, out bool unusable)
        {
            var problems = new List<string>();
            const string rebuild = " Run python3 Tools/build_tools.py from the project root.";
            unusable = false;
            string injector = Path.Combine(toolsPath, "XLuaHotfixInject.exe");
            if (!File.Exists(injector))
            {
                unusable = true;
                problems.Add("Hotfix: HOTFIX_ENABLE is defined, but " + fullPath(injector) + " is missing." + rebuild);
                return problems;
            }
            string manifest = Path.Combine(toolsPath, HotfixManifest);
            if (!File.Exists(manifest))
            {
                problems.Add("Hotfix: " + fullPath(manifest) + " is missing, so the tools in " + fullPath(toolsPath)
                    + " were built by an older build_tools.py and may lack files or fixes." + rebuild);
                return problems;
            }
            string builtFrom = null;
            foreach (var line in File.ReadAllLines(manifest))
            {
                if (line.StartsWith("file=", StringComparison.Ordinal))
                {
                    string file = Path.Combine(toolsPath, line.Substring("file=".Length));
                    if (!File.Exists(file))
                    {
                        unusable = true;
                        problems.Add("Hotfix: " + fullPath(file) + " is missing; the injector needs it." + rebuild);
                    }
                }
                else if (line.StartsWith("hotfix-source-sha256=", StringComparison.Ordinal))
                {
                    builtFrom = line.Substring("hotfix-source-sha256=".Length).Trim();
                }
            }
            if (hotfixSource != null && File.Exists(hotfixSource) && builtFrom != HotfixSourceHash(hotfixSource))
            {
                problems.Add("Hotfix: the injector in " + fullPath(toolsPath) + " was built from a different "
                    + Path.GetFileName(hotfixSource) + " than " + fullPath(hotfixSource) + "." + rebuild);
            }
            return problems;
        }

        // SHA-256 of a source file without its UTF-8 BOM and carriage returns, the
        // same value build_tools.py writes, so line endings do not matter.
        public static string HotfixSourceHash(string path)
        {
            byte[] data = File.ReadAllBytes(path);
            int start = data.Length >= 3 && data[0] == 0xEF && data[1] == 0xBB && data[2] == 0xBF ? 3 : 0;
            var text = new List<byte>(data.Length);
            for (int i = start; i < data.Length; i++)
            {
                if (data[i] != (byte)'\r') text.Add(data[i]);
            }
            using (var sha = System.Security.Cryptography.SHA256.Create())
            {
                return string.Concat(sha.ComputeHash(text.ToArray()).Select(b => b.ToString("x2")).ToArray());
            }
        }

        // The project's copy of xLua's Hotfix.cs (null outside Unity or when not found).
        public static string FindHotfixSource()
        {
#if !XLUA_GENERAL
            foreach (var guid in AssetDatabase.FindAssets("Hotfix t:MonoScript"))
            {
                string path = AssetDatabase.GUIDToAssetPath(guid);
                if (path.EndsWith("/Editor/Hotfix.cs", StringComparison.Ordinal)) return path;
            }
#endif
            return null;
        }

        const BindingFlags anyMember = BindingFlags.Public | BindingFlags.NonPublic | BindingFlags.Instance | BindingFlags.Static;

        // Configuration lists ([LuaCallCSharp] static List<Type> ... in a static
        // class): only the removed Generate Code read them, and the source
        // generator reads the attribute forms (it reports such lists as info
        // XLSG011). [BlackList] lists are still read by the reflection wrappers
        // in the Editor and outside Unity (BlackListRules), so their entries are
        // checked too: an entry that names a renamed type or member silently
        // does nothing. [Hotfix] lists still choose what the injector injects,
        // without bridges, and are the only form for an assembly that cannot
        // reference xLua (an asmdef in the Assembly-CSharp layout), so their
        // message says when to keep one. Names resolve against types.
        static void checkConfig(List<string> problems, List<Type> types)
        {
            foreach (var list in Generator.ConfigurationLists(types))
            {
                if (list.Value == "Hotfix")
                {
                    problems.Add("Configuration list: " + list.Key + " ([Hotfix]) is not read by the xLua source generator, only by the "
                        + "hotfix injector, which gets no hotfix bridges for its types: they must be HotfixFlag.Inline. Convert it with "
                        + "XLua > Migrate Configuration to Attributes (XLuaGenerate --migrate), then delete it, unless the types' assembly "
                        + "cannot reference xLua; then keep it with HotfixFlag.Inline.");
                    continue;
                }
                problems.Add("Configuration list: " + list.Key + " ([" + list.Value + "]) is not read by the xLua source generator"
                    + (list.Value == "BlackList" ? ", only by the reflection wrappers in the Editor" : "")
                    + ". Convert it with XLua > Migrate Configuration to Attributes (XLuaGenerate --migrate), then delete it.");
            }
            Generator.GetGenConfig(types.Where(t => !t.IsGenericTypeDefinition));
            var byName = new Dictionary<string, Type>(StringComparer.Ordinal);
            foreach (var t in types.Concat(XLua.Utils.GetAllTypes()).Concat(Generator.LuaCallCSharp).Concat(Generator.ReflectionUse))
            {
                string name = t.ToString();
                if (!byName.ContainsKey(name)) byName.Add(name, t);
            }

            foreach (var entry in Generator.BlackList)
            {
                string text = entry == null ? "null" : "{" + string.Join(", ", entry.Select(e => "\"" + e + "\"").ToArray()) + "}";
                if (entry == null || entry.Count < 2)
                {
                    problems.Add("BlackList: entry " + text + " needs a type name and a member name.");
                    continue;
                }
                Type type;
                if (!byName.TryGetValue(entry[0], out type))
                {
                    problems.Add("BlackList: entry " + text + " names type " + entry[0] + ", which does not exist.");
                    continue;
                }
                // xLua compares the declaring type, so inherited members do not match.
                var members = type.GetMember(entry[1], anyMember | BindingFlags.DeclaredOnly);
                if (members.Length == 0)
                {
                    problems.Add("BlackList: entry " + text + ": " + type + " declares no member " + entry[1] + ".");
                    continue;
                }
                if (entry.Count > 2)
                {
                    var parameterTypes = entry.Skip(2).ToList();
                    bool found = members.OfType<MethodBase>().Any(m => m.GetParameters().Select(p => p.ParameterType.ToString()).SequenceEqual(parameterTypes));
                    if (!found)
                    {
                        problems.Add("BlackList: entry " + text + ": no " + type + "." + entry[1] + " overload takes ("
                            + string.Join(", ", parameterTypes.ToArray()) + ").");
                    }
                }
            }

        }

        static string fullPath(string path)
        {
            if (string.IsNullOrEmpty(path)) return "(not set)";
            try
            {
                return Path.GetFullPath(path);
            }
            catch (Exception)
            {
                return path;
            }
        }

        static bool hasConfiguration(object[] attributes, out bool callLua)
        {
            callLua = false;
            bool any = false;
            foreach (var a in attributes)
            {
                string name = a.GetType().FullName;
                if (!configurationAttributes.Contains(name)) continue;

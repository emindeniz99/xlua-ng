		// Indexers whose key can be a string are left to the member lookup (Lua's t.name is t["name"]).
		static PropertyInfo[] withoutStringKeys(PropertyInfo[] props)
		{
			List<PropertyInfo> kept = new List<PropertyInfo>(props.Length);
			for (int i = 0; i < props.Length; i++)
			{
				if (!props[i].GetIndexParameters()[0].ParameterType.IsAssignableFrom(typeof(string)))
				{
					kept.Add(props[i]);
				}
			}
			return kept.ToArray();
		}

		// An `in` or `ref readonly` key is a by-reference parameter (Pair&); Lua
		// passes the value, and PropertyInfo.GetValue and SetValue take it boxed.
		// Without this, reflection matched no key and indexing with it failed
		// ("cannot set (null), no such field" for x[p] = v, Unity editor suite
		// with FORCE_REFLECTION, 2026-10-18).
		static Type indexKeyType(PropertyInfo prop)
		{
			Type key = prop.GetIndexParameters()[0].ParameterType;
			return key.IsByRef ? key.GetElementType() : key;
		}

		// The indexer of props whose key type fits the key at index 2 best
		// (OverloadScore), or -1; the first that matches when no two keys can
		// match the same value with different costs.
		sealed class IndexerKeys
		{
			internal Type[] types;
			internal int[] kinds;
			internal Type[] scoreTypes;
			internal bool scored;

			internal IndexerKeys(PropertyInfo[] props)
			{
				types = new Type[props.Length];
				kinds = new int[props.Length];
				scoreTypes = new Type[props.Length];
				var shapes = new OverloadScore.Shape[props.Length];
				for (int i = 0; i < props.Length; i++)
				{
					types[i] = indexKeyType(props[i]);
					kinds[i] = OverloadScore.KindOf(types[i]);
					scoreTypes[i] = OverloadScore.TypeFor(types[i]);
					shapes[i] = new OverloadScore.Shape { start = 2, types = new Type[] { types[i] }, required = 1 };
				}
				scored = OverloadScore.Needed(shapes);
			}

			internal int Pick(ObjectTranslator translator, RealStatePtr L)
			{
				int best = -1, bestScore = int.MaxValue, number = -1;
				for (int i = 0; i < types.Length; i++)
				{
					int score;
					if (!scored)
					{
						if (translator.Assignable(L, 2, types[i])) return i;
						continue;
					}
					// The check reads what the cost needs (OverloadScore.NumberCheck, CheckedArg).
					int kind = kinds[i];
					if (OverloadScore.IsNumeric(kind) && kind < OverloadScore.KindNullable)
					{
						if (!OverloadScore.NumberCheck(translator, L, 2, types[i], kind, ref number)) continue;
						score = OverloadScore.NumberArg(L, 2, kind, ref number);
					}
					else if (kind == OverloadScore.KindOther)
					{
						score = OverloadScore.CheckedArg(translator, L, 2, types[i]);
						if (score < 0) continue;
					}
					else
					{
						if (!translator.Assignable(L, 2, types[i])) continue;
						score = OverloadScore.Arg(translator, L, 2, kind, scoreTypes[i]);
					}
					if (score < bestScore)
					{
						best = i;
						bestScore = score;
						if (score == 0) break;
					}
				}
				return best;
			}
		}

		static LuaCSFunction genItemGetter(Type type, PropertyInfo[] props)
		{
			props = withoutStringKeys(props);
			if (props.Length == 0)
			{
				return null;
			}
			IndexerKeys keys = new IndexerKeys(props);
			Type[] params_type = keys.types;
			object[] arg = new object[1] { null };
			return (RealStatePtr L) =>
			{
				ObjectTranslator translator = ObjectTranslatorPool.Instance.Find(L);
				object obj = translator.FastGetCSObj(L, 1);
				if (obj == null || !type.IsInstanceOfType(obj))
				{
					return LuaAPI.luaL_error(L, "Expected type " + type + ", but got " + (obj == null ? "null" : obj.GetType().ToString()) + ", while get prop " + props[0].Name);
				}

				int i = keys.Pick(translator, L);
				if (i >= 0)
				{
					PropertyInfo prop = props[i];
					try
					{
						object index = translator.GetArgObject(L, 2, params_type[i]);
						arg[0] = index;
						object ret = prop.GetValue(obj, arg);
						LuaAPI.lua_pushboolean(L, true);
						translator.PushAny(L, ret);
						return 2;
					}
					// As generated code reports a C# exception.
					catch (TargetInvocationException e)
					{
						return LuaAPI.luaL_error(L, "c# exception:" + e.InnerException);
					}
					catch (Exception e)
					{
						return LuaAPI.luaL_error(L, "c# exception:" + e);
					}
				}

				LuaAPI.lua_pushboolean(L, false);
				return 1;
			};
		}

		static LuaCSFunction genItemSetter(Type type, PropertyInfo[] props)
		{
			props = withoutStringKeys(props);
			if (props.Length == 0)
			{
				return null;
			}
			IndexerKeys keys = new IndexerKeys(props);
			Type[] params_type = keys.types;
			object[] arg = new object[1] { null };
			return (RealStatePtr L) =>
			{
				ObjectTranslator translator = ObjectTranslatorPool.Instance.Find(L);
				object obj = translator.FastGetCSObj(L, 1);
				if (obj == null || !type.IsInstanceOfType(obj))
				{
					return LuaAPI.luaL_error(L, "Expected type " + type + ", but got " + (obj == null ? "null" : obj.GetType().ToString()) + ", while set prop " + props[0].Name);
				}

				int i = keys.Pick(translator, L);
				if (i >= 0)
				{
					PropertyInfo prop = props[i];
					try
					{
						arg[0] = translator.GetArgObject(L, 2, params_type[i]);
						object val = translator.GetArgObject(L, 3, prop.PropertyType);
						if (val == null)
						{
							return LuaAPI.luaL_error(L, type.Name + "." + prop.Name + " Expected type " + prop.PropertyType);
						}
						prop.SetValue(obj, val, arg);
						LuaAPI.lua_pushboolean(L, true);

						return 1;
					}
					catch (TargetInvocationException e)
					{
						return LuaAPI.luaL_error(L, "c# exception:" + e.InnerException);
					}
					catch (Exception e)
					{
						return LuaAPI.luaL_error(L, "c# exception:" + e);
					}
				}

				LuaAPI.lua_pushboolean(L, false);
				return 1;
			};
		}


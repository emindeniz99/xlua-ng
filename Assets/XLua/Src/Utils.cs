		// The types that the assembly-level forms of CSharpCallLua, LuaCallCSharp
		// and ReflectionUse in these assemblies name ([assembly: X(typeof(T))]
		// and [assembly: X(typeof(A), typeof(B))]), in assembly order. The
		// source generator reads these forms; the emitted bridges and the
		// reflection wrappers' extension methods read them too, since the
		// configuration lists that said the same are deleted once the
		// migration tool has converted them (Generate Code removed, M11).
		internal static void AddAssemblyConfigTypes(IList<Assembly> assemblies, Type attributeType, List<Type> into)
		{
			for (int i = 0; i < assemblies.Count; i++)
			{
				object[] attributes;
				try
				{
					if (assemblies[i].IsDynamic) continue;
					attributes = assemblies[i].GetCustomAttributes(attributeType, false);
				}
				catch (Exception)
				{
					continue;
				}
				for (int j = 0; j < attributes.Length; j++)
				{
					var types = configuredTypes(attributes[j]);
					if (types == null) continue;
					for (int k = 0; k < types.Length; k++)
					{
						if (types[k] != null) into.Add(types[k]);
					}
				}
			}
		}

		static Type[] configuredTypes(object attribute)
		{
			var csCallLua = attribute as CSharpCallLuaAttribute;
			if (csCallLua != null) return csCallLua.Types;
			var luaCallCs = attribute as LuaCallCSharpAttribute;
			if (luaCallCs != null) return luaCallCs.Types;
			var reflectionUse = attribute as ReflectionUseAttribute;
			if (reflectionUse != null) return reflectionUse.Types;
			return null;
		}

		// A C# exception in a field accessor reads as in generated code
		// ("c# exception:" and the exception), not as one that reached
		// FixCSFunction or LazyReflectionCall.
		static LuaCSFunction genFieldGetter(Type type, FieldInfo field)
		{
			if (field.IsStatic)
			{
				return (RealStatePtr L) =>
				{
					try
					{
						ObjectTranslator translator = ObjectTranslatorPool.Instance.Find(L);
						translator.PushAny(L, field.GetValue(null));
						return 1;
					}
					catch (Exception e)
					{
						return LuaAPI.luaL_error(L, "c# exception:" + e);
					}
				};
			}
			else
			{
				return (RealStatePtr L) =>
				{
					try
					{
						ObjectTranslator translator = ObjectTranslatorPool.Instance.Find(L);
						object obj = translator.FastGetCSObj(L, 1);
						if (obj == null || !type.IsInstanceOfType(obj))
						{
							return LuaAPI.luaL_error(L, "Expected type " + type + ", but got " + (obj == null ? "null" : obj.GetType().ToString()) + ", while get field " + field);
						}

						translator.PushAny(L, field.GetValue(obj));
						return 1;
					}
					catch (Exception e)
					{
						return LuaAPI.luaL_error(L, "c# exception:" + e);
					}
				};
			}
		}

		static LuaCSFunction genFieldSetter(Type type, FieldInfo field)
		{
			if (field.IsStatic)
			{
				return (RealStatePtr L) =>
				{
					try
					{
						ObjectTranslator translator = ObjectTranslatorPool.Instance.Find(L);
						object val = translator.GetArgObject(L, 1, field.FieldType);
						if (field.FieldType.IsValueType() && Nullable.GetUnderlyingType(field.FieldType) == null && val == null)
						{
							return LuaAPI.luaL_error(L, type.Name + "." + field.Name + " Expected type " + field.FieldType);
						}
						field.SetValue(null, val);
						return 0;
					}
					catch (Exception e)
					{
						return LuaAPI.luaL_error(L, "c# exception:" + e);
					}
				};
			}
			else
			{
				return (RealStatePtr L) =>
				{
					try
					{
						ObjectTranslator translator = ObjectTranslatorPool.Instance.Find(L);

						object obj = translator.FastGetCSObj(L, 1);
						if (obj == null || !type.IsInstanceOfType(obj))
						{
							return LuaAPI.luaL_error(L, "Expected type " + type + ", but got " + (obj == null ? "null" : obj.GetType().ToString()) + ", while set field " + field);
						}

						object val = translator.GetArgObject(L, 2, field.FieldType);
						if (field.FieldType.IsValueType() && Nullable.GetUnderlyingType(field.FieldType) == null && val == null)
						{
							return LuaAPI.luaL_error(L, type.Name + "." + field.Name + " Expected type " + field.FieldType);
						}
						field.SetValue(obj, val);
						if (type.IsValueType())
						{
							translator.Update(L, 1, obj);
						}
						return 0;
					}
					catch (Exception e)
					{
						return LuaAPI.luaL_error(L, "c# exception:" + e);
					}
				};
			}
		}

